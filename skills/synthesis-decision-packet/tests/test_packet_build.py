@pytest.mark.parametrize("field", ["title", "row label", "option label", "id"])
def test_e49_a_line_break_in_title_label_or_id_is_refused(field):
    """The paste is one line per field; a packet that builds must also file."""
    current = spec()
    if field == "title":
        current["title"] = "Two\nlines"
    elif field == "row label":
        current["rows"][0]["label"] = "Two\r\nlines"
    elif field == "option label":
        current["options"][0]["label"] = "Ship the fix\nthis week"
    else:
        current["rows"][0]["id"] = "R\n1"
    assert any("line break" in p for p in hard(bp.validate(current)))


def test_e53_fewer_than_five_rows_is_flagged_and_needs_allow_small(tmp_path):
    current = spec(n=3)
