def test_schema_prints_the_spec_format():
    result = cli("--schema")
    assert result.returncode == 0 and "Decision-packet spec (JSON)" in result.stdout
    assert '"carried_from"' in result.stdout and "review_assets" in result.stdout


def test_stdout_and_out_write_the_page(tmp_path):
    path = write(tmp_path, spec())
    printed = cli(path, "--stdout")
    assert printed.returncode == 0 and printed.stdout.startswith("<!doctype html>")
    out = tmp_path / "work" / "packet.html"
    assert cli(path, "-o", out).returncode == 0 and out.read_text(encoding="utf-8") == printed.stdout
    write(tmp_path, spec(title="Revised synthetic choices"))
    assert cli(path, "-o", out).returncode == 0 and "Revised synthetic choices" in out.read_text(encoding="utf-8")


def test_file_into_files_dated_spec_and_page_and_keeps_earlier_versions(tmp_path):
    artifacts = tmp_path / "resources" / "artifacts"
    artifacts.mkdir(parents=True)
    path = write(tmp_path, spec())
    first = cli(path, "--strict-reader", "--file-into", artifacts, "--date", "2026-09-14")
    assert first.returncode == 0, first.stderr
    stem = artifacts / "2026-09-14-synthetic-release-choices"
    spec_copy, page_copy = Path(f"{stem}-spec.json"), Path(f"{stem}.html")
    assert spec_copy.read_bytes() == bp.canonical_spec_bytes(spec())
    assert DOCTOR_MARKER.search(page_copy.read_text(encoding="utf-8"))
    assert cli(path, "--file-into", artifacts, "--date", "2026-09-14").returncode == 0  # identical: idempotent
    assert len(list(artifacts.iterdir())) == 2
    revised = spec()
    revised["rows"][0]["context"] = "Revised fixture."
    write(tmp_path, revised)
    assert cli(path, "--file-into", artifacts, "--date", "2026-09-14").returncode == 0
    assert len(list(artifacts.iterdir())) == 4 and spec_copy.read_bytes() == bp.canonical_spec_bytes(spec())


def test_file_into_needs_an_existing_directory_and_date_needs_file_into(tmp_path):
    path = write(tmp_path, spec())
    missing = cli(path, "--file-into", tmp_path / "nowhere")
    assert missing.returncode == 2 and "not an existing directory" in missing.stderr
    assert cli(path, "--stdout", "--date", "2026-09-14").returncode == 2
    (tmp_path / "a").mkdir()
    assert cli(path, "--file-into", tmp_path / "a", "--date", "2026-02-30").returncode == 2
