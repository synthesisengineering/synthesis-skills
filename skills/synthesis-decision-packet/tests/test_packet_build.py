def test_e54_charset_is_declared_in_the_first_bytes_and_typography_survives(tmp_path):
    """Without the charset first, curly quotes and dashes render as mojibake over a plain
    local HTTP server; the defect reached a real packet and was found by loading the page."""
    curly = "Don’t “converge” first — surface it…"
    current = spec()
    current["rows"][0]["label"] = curly
    page = bp.build(current)
    head = page[:200]
    assert '<meta charset="utf-8">' in head and head.index("<meta charset") < head.index("<title")
    path = tmp_path / "p.html"
    path.write_bytes(page.encode("utf-8"))
    embedded = json.loads(DOCTOR_SPEC.search(path.read_bytes().decode("utf-8")).group(1))
    assert embedded["rows"][0]["label"] == curly


def test_marker_pins_the_embedded_spec_in_the_form_the_context_doctor_reads():
    page = bp.build(spec())
    marker, embedded = DOCTOR_MARKER.search(page), DOCTOR_SPEC.search(page)
    assert marker and embedded
    assert hashlib.sha256(embedded.group(1).encode("utf-8")).hexdigest() == marker.group(1)
    assert page.index(marker.group(0)) < page.index("<style>")


def test_e42_a_fresh_packet_selects_nothing_and_marks_the_recommendation_on_its_control():
    """Pressed state comes from saved choices alone; the recommendation only marks a button.
    A packet that opens decided cannot tell "I agreed" from "I never looked"."""
    page = bp.build(spec())
    assert 'b.setAttribute("aria-pressed", String(b.dataset.value === d))' in page
    body = page.split("<body", 1)[1].split("<script", 1)[0]
    assert 'aria-pressed="true"' not in body
    block = page[page.index("if (row.recommendation === o.value)"):]
    block = block[:block.index("b.addEventListener")]
    assert 'b.dataset.recommended = "true";' in block and "aria-pressed" not in block
    assert 'button[data-recommended="true"]' in page and '"recommended: "' in page


def test_e47_copy_selects_first_reports_synchronously_and_reports_on_every_path():
    """navigator.clipboard is blocked in a sandboxed artifact iframe; in the origin run the
    button did nothing and said nothing. Select first, say something at once, then try."""
    page = bp.build(spec())
    fn = page[page.index("function copySummary"):page.index('document.getElementById("copy").addEventListener')]
    order = [fn.index("ta.select()"), fn.index('status.textContent = "Selected'),
             fn.index("document.execCommand"), fn.index("navigator.clipboard")]
    assert order == sorted(order)
    assert "setTimeout(blocked, 2000)" in fn, "an unsettled clipboard promise must still end in a report"
    assert fn.count("status.textContent") >= 3 and "the text is selected" in fn


def test_e48_spec_text_cannot_close_the_script_block():
    current = spec()
    current["rows"][0]["context"] = "literal </script><script>window.injected=true</script>"
    current["rows"][1]["context"] = "literal <!--<script> sequence"
