@pytest.mark.parametrize("change, expected", [
    (lambda s: s.update(options=[{"value": "only", "label": "Keep them on my phone"}]), "at least two options"),
    (lambda s: s["options"][1].update(value="ship"), "used by more than one option"),
    (lambda s: s["options"][0].update(value=1), "must be a non-empty string"),
    (lambda s: s["options"][0].update(tone="loud"), "tone"),
    (lambda s: s["rows"][0].update(recommendation="publish"), "is not one of its options"),
    (lambda s: [r.pop("recommendation") for r in s["rows"]], "questionnaire"),
    (lambda s: s["rows"][0].update(impact={"accept": "x"}), "impact needs both"),
    (lambda s: s["rows"][0].update(disagreement={"a": {"who": "A", "view": "x"}}), "disagreement needs both"),
    (lambda s: s["rows"][0].update(links=[{"label": "x", "href": "javascript:alert(1)"}]), "scheme"),
    (lambda s: s["rows"][0].update(prior_position={"statement": "x"}), "prior_position"),
    (lambda s: s.update(glossary=[{"term": "holdout"}]), "glossary"),
    (lambda s: s["rows"][0].update(severity="urgent"), "severity"),
])
def test_malformed_specs_are_refused_before_anything_is_written(change, expected):
    current = spec()
    change(current)
    assert any(expected in p for p in hard(bp.validate(current))), bp.validate(current)


def test_strict_json_refuses_duplicate_keys_and_nonfinite_numbers(tmp_path):
    for raw in ('{"title": "a", "title": "b"}', '{"title": NaN}'):
        path = tmp_path / "bad.json"
        path.write_text(raw, encoding="utf-8")
        result = cli(path, "--stdout")
        assert result.returncode == 2 and "cannot read valid spec JSON" in result.stderr


