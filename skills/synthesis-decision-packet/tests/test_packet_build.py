DOCTOR_MARKER = re.compile(r"<!-- synthesis-decision-packet spec-sha256:([0-9a-f]{64}) -->")
DOCTOR_SPEC = re.compile(r'<script type="application/json" id="spec">(.*?)</script>', re.S)


def spec(n=5, **over):
    """A reader-compliant synthetic packet."""
    s = {
        "title": "Synthetic release choices",
        "audience": "A fixture principal who has not read the review.",
        "options": [{"value": "ship", "label": "Ship the fix this week", "tone": "ok"},
                    {"value": "hold", "label": "Leave the code as it stands", "tone": "warn"}],
        "rows": [{"id": f"R-{i}", "label": f"Synthetic finding {i}", "context": "Fixture only.",
                  "impact": {"accept": "The fixture changes.", "decline": "The fixture stays."},
                  "recommendation": "ship"} for i in range(1, n + 1)],
    }
    s.update(over)
    return s


def hard(problems):
    return [p for p in problems if not p.startswith(("NOTE:", "READER:"))]


def cli(*args, stdin=None):
    return subprocess.run([sys.executable, str(SCRIPTS / "build_packet.py"), *map(str, args)],
                          input=stdin, capture_output=True, text=True)


def write(tmp_path, value, name="spec.json"):
    path = tmp_path / name
    path.write_text(json.dumps(value, ensure_ascii=False), encoding="utf-8")
    return path


def png(width=2, height=2):
    """A valid PNG; a large declared size gets a token pixel stream, enough for header checks."""
    def chunk(kind, data):
        return len(data).to_bytes(4, "big") + kind + data + zlib.crc32(kind + data).to_bytes(4, "big")
    header = width.to_bytes(4, "big") + height.to_bytes(4, "big") + b"\x08\x02\x00\x00\x00"
    rows = height if width * height <= 64 else 1
    pixels = zlib.compress(b"".join(b"\x00" + b"\xff\x00\x00" * min(width, 8) for _ in range(rows)))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", pixels) + chunk(b"IEND", b"")


def text_asset(aid, kind, text):
    return {"id": aid, "title": f"Synthetic {kind}", "kind": kind,
            "content": {"text": text, "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest()}}


def image_asset(data, aid="screenshot"):
    return {"id": aid, "title": "Synthetic screenshot", "kind": "image", "filename": "screenshot.png",
            "description": "A two-pixel synthetic image.",
            "content": {"base64": base64.b64encode(data).decode("ascii"), "sha256": hashlib.sha256(data).hexdigest(),
                        "size": len(data), "media_type": "image/png"}}


def review_row(assets):
    return {"revision": "draft-1", "review_assets": assets,
            "delivery": {"format": "Plain text email", "destinations": ["To: reader@example.test"], "attachments": []}}


