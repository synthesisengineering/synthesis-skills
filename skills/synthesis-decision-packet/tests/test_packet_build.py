def test_e52_review_material_is_embedded_and_nothing_is_fetched(monkeypatch):
    """An image, a code excerpt and a draft email are shown inside the packet; an
    unavailable item keeps its link but nothing is fetched, at build time or by the page."""
    def no_network(*_args, **_kwargs):
        raise AssertionError("the generator must not touch the network")
    monkeypatch.setattr(socket, "socket", no_network)
    monkeypatch.setattr(urllib.request, "urlopen", no_network)
    email = "To: reader@example.test\nSubject: Synthetic draft\n\nHello, fixture."
    current = spec()
    current["rows"][0].update(review_row([text_asset("draft", "correspondence", email),
                                          text_asset("excerpt", "code", "def fixture():\n    return 1\n"),
                                          image_asset(png())]))
    current["rows"][1].update(review_row([{"id": "missing", "title": "Remote file", "kind": "document",
                                           "description": "Not supplied.",
                                           "content": {"unavailable": "Not supplied to the agent",
                                                       "source": "https://example.invalid/file.pdf"}}]))
    assert not hard(bp.validate(current))
    page = bp.build(current)
    embedded = json.loads(DOCTOR_SPEC.search(page).group(1))
    assert embedded["rows"][0]["review_assets"][0]["content"]["text"] == email
    assert embedded["rows"][0]["review_assets"][2]["content"]["base64"] == base64.b64encode(png()).decode()
    assert "media.src = 'data:' + content.media_type" in page and "No content was fetched." in page
    assert bp.review_assets_ready(current["rows"][0]) and not bp.review_assets_ready(current["rows"][1])
    assert "b.disabled = !assetsReady(row);" in page


@pytest.mark.parametrize("mutate", [
    lambda a: a["content"].update(sha256="0" * 64),
    lambda a: a["content"].update(base64="not base64!"),
    lambda a: a["content"].update(media_type="image/gif"),
    lambda a: a.update(filename="../screenshot.png"),
    lambda a: a.pop("description"),
    lambda a: a.update(kind="executable"),
    lambda a: a["content"].update(base64=base64.b64encode(png(9000, 9000)).decode(),
                                  size=len(png(9000, 9000)), sha256=hashlib.sha256(png(9000, 9000)).hexdigest()),
    lambda a: a.update(content={"unavailable": "missing", "source": "file:///etc/hosts"}),
])
def test_review_material_refusals(mutate):
    current = spec()
    asset = image_asset(png())
    mutate(asset)
    current["rows"][0].update(review_row([asset]))
    assert hard(bp.validate(current))


