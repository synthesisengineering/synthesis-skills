def test_e54_charset_is_declared_in_the_first_bytes_and_typography_survives(tmp_path):
    """Without the charset first, curly quotes and dashes render as mojibake over a plain
    local HTTP server; the defect reached a real packet and was found by loading the page."""
    curly = "Don’t “converge” first — surface it…"
    current = spec()
    current["rows"][0]["label"] = curly
    page = bp.build(current)
    head = page[:200]
    assert '<meta charset="utf-8">' in head and head.index("<meta charset") < head.index("<title")
    path = tmp_path / "p.html"
    path.write_bytes(page.encode("utf-8"))
    embedded = json.loads(DOCTOR_SPEC.search(path.read_bytes().decode("utf-8")).group(1))
    assert embedded["rows"][0]["label"] == curly


def test_marker_pins_the_embedded_spec_in_the_form_the_context_doctor_reads():
    page = bp.build(spec())
    marker, embedded = DOCTOR_MARKER.search(page), DOCTOR_SPEC.search(page)
    assert marker and embedded
    assert hashlib.sha256(embedded.group(1).encode("utf-8")).hexdigest() == marker.group(1)
    assert page.index(marker.group(0)) < page.index("<style>")


def test_e42_a_fresh_packet_selects_nothing_and_marks_the_recommendation_on_its_control():
    """Pressed state comes from saved choices alone; the recommendation only marks a button.
    A packet that opens decided cannot tell "I agreed" from "I never looked"."""
    page = bp.build(spec())
    assert 'b.setAttribute("aria-pressed", String(b.dataset.value === d))' in page
    body = page.split("<body", 1)[1].split("<script", 1)[0]
    assert 'aria-pressed="true"' not in body
    block = page[page.index("if (row.recommendation === o.value)"):]
    block = block[:block.index("b.addEventListener")]
    assert 'b.dataset.recommended = "true";' in block and "aria-pressed" not in block
    assert 'button[data-recommended="true"]' in page and '"recommended: "' in page


def test_e47_copy_selects_first_reports_synchronously_and_reports_on_every_path():
    """navigator.clipboard is blocked in a sandboxed artifact iframe; in the origin run the
    button did nothing and said nothing. Select first, say something at once, then try."""
    page = bp.build(spec())
    fn = page[page.index("function copySummary"):page.index('document.getElementById("copy").addEventListener')]
    order = [fn.index("ta.select()"), fn.index('status.textContent = "Selected'),
             fn.index("document.execCommand"), fn.index("navigator.clipboard")]
    assert order == sorted(order)
    assert "setTimeout(blocked, 2000)" in fn, "an unsettled clipboard promise must still end in a report"
    assert fn.count("status.textContent") >= 3 and "the text is selected" in fn


def test_e48_spec_text_cannot_close_the_script_block():
    current = spec()
    current["rows"][0]["context"] = "literal </script><script>window.injected=true</script>"
    current["rows"][1]["context"] = "literal <!--<script> sequence"
    page = bp.build(current)
    payload = DOCTOR_SPEC.search(page).group(1)
    assert "<" not in payload
    assert page.count("</script>") == 2
    assert json.loads(payload) == {**current, "storage_key": bp.slugify(current["title"]), "filters": []}


def test_page_is_self_contained():
    page = bp.build(spec())
    assert not re.search(r'<(script|img|link|iframe)[^>]+(src|href)="(https?:)?//', page)
    assert "fetch(" not in page and "XMLHttpRequest" not in page


def test_each_button_carries_its_consequence_and_the_row_shows_impact_both_ways():
    current = spec()
    current["rows"][0]["options"] = [
        {"value": "ship", "label": "Ship the fix this week", "consequence": "The release waits a day."},
        {"value": "hold", "label": "Leave the code as it stands", "consequence": "The bug ships."}]
    page = bp.build(current)
    assert "if (o.consequence) return o.consequence;" in page
    assert "row.recommendation === o.value ? row.impact.accept : row.impact.decline" in page
    assert "If you take the recommendation:" in page
    assert not hard(bp.validate(current))


# --- refusals ---------------------------------------------------------------------------

@pytest.mark.parametrize("labels", [("Yes", "No"), ("Approve", "Reject"), ("Yes, do that", "No thanks"),
                                    ("Accept it", "Decline"), ("Do that", "Stop"), ("OK", "Cancel")])
def test_e43_bare_labels_are_refused_under_strict_reader_with_the_accepted_form(tmp_path, labels):
    """Measured 2026-09-14: rows offering "Yes, do that" / "No" collected notes instead of
    decisions because the principal could not tell what each button would do."""
    current = spec()
    current["rows"][2]["options"] = [{"value": "a", "label": labels[0]}, {"value": "b", "label": labels[1]}]
    current["rows"][2]["recommendation"] = "a"
    findings = [p for p in bp.validate(current) if p.startswith("READER:")]
    assert findings and "R-3" in findings[0] and repr(labels[0]) in findings[0]
    path = write(tmp_path, current)
    refused = cli(path, "--strict-reader", "-o", tmp_path / "p.html")
    assert refused.returncode == 2 and not (tmp_path / "p.html").exists()
    assert bp.ACCEPTED_LABEL_FORM in refused.stderr and "--strict-reader" in refused.stderr
    assert cli(path, "-o", tmp_path / "p.html").returncode == 0  # a warning without strictness


def test_labels_sharing_every_content_word_raise_a_reader_finding():
    current = spec(options=[{"value": "keep", "label": "Keep it"}, {"value": "keep2", "label": "Keep that"}])
    for row in current["rows"]:
        row["recommendation"] = "keep"
    assert any("bare" in p or "content word" in p for p in bp.validate(current) if p.startswith("READER:"))
    current["options"][1]["label"] = "Keep them on my phone"
    current["options"][0]["label"] = "Take them off my phone"
    assert not [p for p in bp.validate(current) if p.startswith("READER:")]


def test_reader_contract_findings_warn_by_default_and_refuse_under_strict_reader(tmp_path):
    current = spec()
    del current["audience"]
    del current["rows"][0]["impact"]
    reader = [p for p in bp.validate(current) if p.startswith("READER:")]
    assert len(reader) == 2 and "R-1" in reader[1]
    path = write(tmp_path, current)
    assert cli(path, "--strict-reader", "--stdout").returncode == 2
    assert cli(path, "--stdout").returncode == 0


def test_e44_ids_that_collide_after_browser_coercion_are_refused(tmp_path):
    """JSON 1 and "1" become the same browser storage key."""
    current = spec()
    current["rows"][0]["id"], current["rows"][1]["id"] = 1, "1"
    assert any("must be a non-empty string" in p for p in bp.validate(current))
    result = cli(write(tmp_path, current), "-o", tmp_path / "p.html")
    assert result.returncode == 2 and not (tmp_path / "p.html").exists()


