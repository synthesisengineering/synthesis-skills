def git(args, cwd=None, timeout=300):
    return run(["git"] + args, cwd=cwd, timeout=timeout)


def configured_git_identity():
    name = str(
        os.environ.get("GIT_AUTHOR_NAME")
        or os.environ.get("GIT_COMMITTER_NAME")
        or ""
    ).strip()
    email = str(
        os.environ.get("GIT_AUTHOR_EMAIL")
        or os.environ.get("GIT_COMMITTER_EMAIL")
        or ""
    ).strip()
    if not name:
        rc, out, _ = git(["config", "--global", "--get", "user.name"])
        if rc == 0:
            name = out.strip()
    if not email:
        rc, out, _ = git(["config", "--global", "--get", "user.email"])
        if rc == 0:
            email = out.strip()
    return (name, email) if name and email else None


def origin_url(repo):
    rc, out, _ = git(["remote", "get-url", "origin"], cwd=repo)
    return out.strip() if rc == 0 else None


def is_dirty(repo):
    rc, out, _ = git(["status", "--porcelain"], cwd=repo)
    return bool(out.strip()) if rc == 0 else True


def clone_or_update(report, phase, url_list, dest, dry_run, allow_stale=ALLOW_STALE):
    """Ensure dest is a clone of url_list[0] (fallbacks tried on fresh clone).
    Fail LOUD when an existing cache cannot be refreshed (no silent stale)."""
    dest = Path(dest)
    if (dest / ".git").exists():
        rc, _, err = git(["pull", "--ff-only"], cwd=dest, timeout=180)
        if rc == 0:
            return report.add(phase, OK, "%s is current" % dest)
        if allow_stale:
            return report.add(phase, WARN, "%s could not refresh; continuing with cached copy (allow-stale)" % dest,
                              hint=err.strip()[-300:] if err else None)
        return report.add(phase, ERROR, "%s exists but could not refresh — refusing stale content" % dest,
                          hint="Fix network/auth and re-run, or set SYNTHESIS_ONBOARD_ALLOW_STALE=1 to accept the cached copy.\n%s" % (err.strip()[-300:] if err else ""))
    if dry_run:
        return report.add(phase, CHANGED, "would clone %s -> %s" % (url_list[0], dest))
    dest.parent.mkdir(parents=True, exist_ok=True)
    last_err = ""
    for url in url_list:
        rc, _, err = git(["clone", url, str(dest)], timeout=600)
        if rc == 0:
            return report.add(phase, CHANGED, "cloned %s" % url)
        last_err = err.strip()
    return report.add(phase, ERROR, "could not clone %s" % url_list[0], hint=last_err[-400:])


