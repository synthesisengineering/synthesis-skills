RECEIPTS_PATH = STATE_DIR / "receipts.json"
ALLOW_STALE = os.environ.get("SYNTHESIS_ONBOARD_ALLOW_STALE", "") == "1"

GENERATED_MARK = "generated by synthesis-onboarding"

OK, CHANGED, WOULD, ACTION, WARN, ERROR, SKIP = (
    "ok", "changed", "would-change", "action-needed", "warning", "error", "skipped")
_BADGES = {OK: "  ok", CHANGED: "  ++", WOULD: "  ~~", ACTION: "  !!", WARN: "  ?!", ERROR: "  XX", SKIP: "  --"}


def utcnow():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def run(cmd, cwd=None, env=None, timeout=300):
    """Run a command; return (rc, stdout, stderr). Never raises on rc!=0."""
    merged = dict(os.environ)
    if env:
        merged.update(env)
    try:
        proc = subprocess.run(
            cmd, cwd=str(cwd) if cwd else None, env=merged, timeout=timeout,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        return proc.returncode, proc.stdout, proc.stderr
    except FileNotFoundError as exc:
        return 127, "", str(exc)
    except subprocess.TimeoutExpired:
        return 124, "", "timeout after %ss: %s" % (timeout, " ".join(map(str, cmd)))


class Report:
    """Collects step results; renders text or JSON; tracks exit code."""

    def __init__(self, dry_run=False, as_json=False):
        self.steps = []
        self.dry_run = dry_run
        self.as_json = as_json

    def add(self, phase, status, detail, hint=None):
        if self.dry_run and status == CHANGED:
            status = WOULD
        self.steps.append({"phase": phase, "status": status, "detail": detail, "hint": hint})
        if not self.as_json:
            line = "%s [%s] %s" % (_BADGES.get(status, "  ??"), phase, detail)
            print(line)
            if hint:
                for hline in hint.strip().splitlines():
                    print("        %s" % hline)
        return status

    def counts(self):
        out = {}
        for step in self.steps:
            out[step["status"]] = out.get(step["status"], 0) + 1
        return out

    def exit_code(self):
        counts = self.counts()
        if counts.get(ERROR):
            return 1
        if counts.get(ACTION):
            return 1
        return 0


