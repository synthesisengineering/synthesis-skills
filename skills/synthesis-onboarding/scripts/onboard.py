def _coerce_scalar(token):
    token = token.strip()
    if token.startswith('"') and token.endswith('"') and len(token) >= 2:
        return token[1:-1]
    if token.startswith("'") and token.endswith("'") and len(token) >= 2:
        return token[1:-1]
    lowered = token.lower()
    if lowered in ("true", "yes"):
        return True
    if lowered in ("false", "no"):
        return False
    if lowered in ("null", "~", ""):
        return None
    if re.fullmatch(r"-?\d+", token):
        return int(token)
    return token


def parse_subset_yaml(text, source="manifest"):
    """Parse the documented YAML subset: nested maps, lists ('- '), scalars,
    literal blocks ('|'), full-line comments. Raises ValueError with line
    numbers on anything outside the subset (fail closed, no guessing)."""
    lines = text.splitlines()
    items = []  # (indent, kind, payload, lineno); kind: kv, key, list_scalar, list_map_start
    index = 0
    while index < len(lines):
        raw = lines[index]
        lineno = index + 1
        stripped = raw.strip()
        index += 1
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        if raw.lstrip(" ").startswith("- "):
            body = raw.lstrip(" ")[2:]
            key_candidate = body.split(":", 1)[0].strip()
            looks_like_map = (": " in body or body.endswith(":")) and \
                re.fullmatch(r"[A-Za-z0-9_-]+", key_candidate) and not body.startswith(("'", '"'))
            if looks_like_map:
                items.append((indent, "list_map_start", body, lineno))
            else:
                items.append((indent, "list_scalar", body, lineno))
            continue
        if ":" not in stripped:
            raise ValueError("%s:%d: expected 'key: value', got %r" % (source, lineno, stripped))
        key, _, rest = stripped.partition(":")
        rest = rest.strip()
        if rest == "|":
            block = []
            block_indent = None
            while index < len(lines):
                nxt = lines[index]
                if nxt.strip() == "":
                    block.append("")
                    index += 1
                    continue
                nxt_indent = len(nxt) - len(nxt.lstrip(" "))
                if nxt_indent <= indent:
                    break
                if block_indent is None:
                    block_indent = nxt_indent
                block.append(nxt[block_indent:])
                index += 1
            while block and block[-1] == "":
                block.pop()
            items.append((indent, "kv", (key.strip(), "\n".join(block) + "\n"), lineno))
        elif rest == "":
            items.append((indent, "key", key.strip(), lineno))
        else:
            items.append((indent, "kv", (key.strip(), _coerce_scalar(rest)), lineno))

    def build(start, end, indent):
        if start >= end:
            return {}
        kind = items[start][1]
        if kind in ("list_scalar", "list_map_start"):
            result = []
            pos = start
            while pos < end:
                item_indent, item_kind, payload, lineno = items[pos]
                if item_indent != indent:
                    raise ValueError("%s:%d: inconsistent list indentation" % (source, lineno))
                if item_kind == "list_scalar":
                    result.append(_coerce_scalar(payload))
                    pos += 1
                    continue
                # list item opening an inline map: '- key: value'
                sub_end = pos + 1
                while sub_end < end and items[sub_end][0] > indent:
                    sub_end += 1
                key, _, rest = payload.partition(":")
                entry = {}
                rest = rest.strip()
                if rest:
                    entry[key.strip()] = _coerce_scalar(rest)
                elif pos + 1 < sub_end:
                    raise ValueError("%s:%d: '- key:' with nested block is outside the subset; use '- key: value' pairs" % (source, lineno))
                child = build(pos + 1, sub_end, items[pos + 1][0]) if pos + 1 < sub_end else {}
                if child and not isinstance(child, dict):
                    raise ValueError("%s:%d: list items must be scalars or flat maps" % (source, lineno))
                entry.update(child or {})
                result.append(entry)
                pos = sub_end
            return result
        result = {}
        pos = start
        while pos < end:
            item_indent, item_kind, payload, lineno = items[pos]
            if item_indent != indent:
                raise ValueError("%s:%d: inconsistent map indentation" % (source, lineno))
            if item_kind == "kv":
                key, value = payload
                if key in result:
                    raise ValueError("%s:%d: duplicate key %r" % (source, lineno, key))
                result[key] = value
                pos += 1
            elif item_kind == "key":
                sub_end = pos + 1
                while sub_end < end and items[sub_end][0] > indent:
                    sub_end += 1
                if sub_end == pos + 1:
                    result[payload] = None
                else:
                    result[payload] = build(pos + 1, sub_end, items[pos + 1][0])
                pos = sub_end
            else:
                raise ValueError("%s:%d: list item where a key was expected" % (source, lineno))
        return result

    return build(0, len(items), items[0][0] if items else 0)


TOP_KEYS = {"version", "org", "ecosystem", "skills_repos", "knowledge_bases",
            "auth_help", "welcome", "migrations", "workspace_instructions"}
ORG_KEYS = {"id", "name", "workspace"}
SKILLS_REPO_KEYS = {"name", "primary", "fallbacks", "installer", "installer_args",
                    "source_env", "status_args"}
KB_KEYS = {"name", "primary", "superseded_remotes", "local_hooks", "default_branch"}
WELCOME_KEYS = {"title", "try_asking", "docs"}
MIGRATION_KEYS = {"from", "action", "to", "note"}


def _require(cond, message):
    if not cond:
        raise ValueError("manifest: %s" % message)


def validate_manifest(data, path):
    _require(isinstance(data, dict), "top level must be a mapping")
    unknown = set(data) - TOP_KEYS
    _require(not unknown, "unknown top-level keys: %s (fail-closed; see org-manifest.md)" % ", ".join(sorted(unknown)))
    _require(data.get("version") == 1, "version must be 1")
    org = data.get("org") or {}
    _require(isinstance(org, dict) and not set(org) - ORG_KEYS, "org block has unknown keys")
    _require(org.get("id") and org.get("workspace"), "org.id and org.workspace are required")
    for repo in data.get("skills_repos") or []:
        _require(isinstance(repo, dict) and not set(repo) - SKILLS_REPO_KEYS,
                 "skills_repos entry has unknown keys: %r" % repo)
        _require(repo.get("name") and repo.get("primary"), "skills_repos entries need name + primary")
    for kb in data.get("knowledge_bases") or []:
        _require(isinstance(kb, dict) and not set(kb) - KB_KEYS,
                 "knowledge_bases entry has unknown keys: %r" % kb)
        _require(kb.get("name") and kb.get("primary"), "knowledge_bases entries need name + primary")
    welcome = data.get("welcome") or {}
    _require(isinstance(welcome, dict) and not set(welcome) - WELCOME_KEYS, "welcome block has unknown keys")
    migrations = data.get("migrations") or {}
    _require(isinstance(migrations, dict) and not set(migrations) - {"skills"}, "migrations supports only 'skills'")
    for mig in migrations.get("skills") or []:
        _require(isinstance(mig, dict) and not set(mig) - MIGRATION_KEYS, "migration entry has unknown keys")
        _require(mig.get("from") and mig.get("action") in ("remove", "rename"),
                 "migrations.skills entries need from + action (remove|rename)")
        if mig.get("action") == "rename":
            _require(mig.get("to"), "rename migrations need 'to'")
    data.setdefault("_path", str(path))
    return data


def load_manifest(path):
    text = Path(path).read_text(encoding="utf-8")
    try:
        import yaml  # type: ignore
        data = yaml.safe_load(text)
    except ImportError:
        data = parse_subset_yaml(text, source=str(path))
    return validate_manifest(data, path)


