class Receipts:
    def __init__(self, path=RECEIPTS_PATH):
        self.path = Path(path)
        if self.path.exists():
            self.data = json.loads(self.path.read_text(encoding="utf-8"))
        else:
            self.data = {"version": 1, "generated_files": {}, "adopted_repos": {}, "runs": []}

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        os.replace(tmp, self.path)

    def file_sha(self, path):
        return (self.data["generated_files"].get(str(path)) or {}).get("sha256")

    def record_file(self, path, content, kind):
        self.data["generated_files"][str(path)] = {
            "sha256": sha256_text(content), "kind": kind, "written_at": utcnow(),
            "engine": ENGINE_VERSION}

    def forget_file(self, path):
        self.data["generated_files"].pop(str(path), None)

    def adopted(self, name):
        return self.data["adopted_repos"].get(name)

    def record_adoption(self, name, path):
        self.data["adopted_repos"][name] = str(path)


def archive_path(target):
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    dest = STATE_DIR / "backups" / stamp / target.name
    dest.parent.mkdir(parents=True, exist_ok=True)
    return dest


def ensure_file(report, receipts, path, content, kind, dry_run):
    """Conffile-semantics write. Returns final status."""
    path = Path(path)
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            receipts.record_file(path, content, kind)
            return report.add(kind, OK, "%s is current" % path)
        owned = receipts.file_sha(path) == sha256_text(current)
        if not owned and GENERATED_MARK not in current:
            return report.add(kind, WARN,
                              "%s exists with your own edits — left untouched" % path,
                              hint="Remove the file and re-run to regenerate it.")
        if dry_run:
            return report.add(kind, CHANGED, "would update %s (backup kept)" % path)
        backup = archive_path(path)
        shutil.copy2(path, backup)
        path.write_text(content, encoding="utf-8")
        receipts.record_file(path, content, kind)
        return report.add(kind, CHANGED, "updated %s (previous copy archived)" % path)
    if dry_run:
        return report.add(kind, CHANGED, "would create %s" % path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    receipts.record_file(path, content, kind)
    return report.add(kind, CHANGED, "created %s" % path)


