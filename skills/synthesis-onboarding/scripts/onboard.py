CLIENT_WELL_KNOWN = {
    "claude": [HOME / ".local/bin/claude", Path("/usr/local/bin/claude"),
               Path("/opt/homebrew/bin/claude")],
    "codex": [Path("/Applications/ChatGPT.app/Contents/Resources/codex"),
              Path("/usr/local/bin/codex"), Path("/opt/homebrew/bin/codex")],
}


def resolve_client(name):
    env_key = "SYNTHESIS_%s_BIN" % name.upper()
    if env_key in os.environ:
        value = os.environ[env_key].strip()
        return value or None  # set-but-empty means "treat as absent"
    found = shutil.which(name)
    if found:
        return found
    for candidate in CLIENT_WELL_KNOWN.get(name, []):
        if candidate.exists():
            return str(candidate)
    return None


def plugin_enabled(client, binary):
    rc, out, _ = run([binary, "plugin", "list", "--json"], timeout=60)
    if rc != 0:
        return None  # unknown — CLI unavailable or errored
    try:
        entries = json.loads(out)
    except ValueError:
        return PLUGIN_NAME in out and '"enabled": true' in out
    if isinstance(entries, dict):
        # claude nests under "plugins"; codex nests under "installed"
        flat = []
        for value in entries.values():
            if isinstance(value, list):
                flat.extend(value)
        entries = flat
    for entry in entries or []:
        if not isinstance(entry, dict) or not entry.get("enabled", False):
            continue
        ident = str(entry.get("id") or entry.get("pluginId") or "")
        if ident.startswith(PLUGIN_NAME + "@") or entry.get("name") == PLUGIN_NAME:
            return True
    return False


def install_plugin(client, binary):
    """Best-effort native plugin install. Returns (success, detail)."""
    add_cmd = [binary, "plugin", "marketplace", "add", PUBLIC_MARKETPLACE_REF]
    rc, out, err = run(add_cmd, timeout=180)
    if rc != 0 and "already" not in (out + err).lower():
        return False, "marketplace add failed: %s" % (err.strip() or out.strip())
    verb = "install" if client == "claude" else "add"
    rc, out, err = run([binary, "plugin", verb, "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)], timeout=300)
    if rc != 0 and "already" not in (out + err).lower():
        return False, "plugin %s failed: %s" % (verb, err.strip() or out.strip())
    return True, "installed via %s CLI" % client


def source_root():
    override = os.environ.get("SYNTHESIS_ONBOARD_SOURCE_DIR")
    if override:
        return Path(override)
    return Path(__file__).resolve().parents[3]


