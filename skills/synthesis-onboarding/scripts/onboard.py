#!/usr/bin/env python3
"""synthesis-onboarding engine.

Converges a machine toward a working synthesis ecosystem install:

  install         (default) converge everything; safe to re-run anytime
  update          alias of install
  doctor          verify-only; exit 0 healthy / 1 defects / 2 cannot verify
  init-workspace  scaffold ~/workspaces/<name>/ai-knowledge-<name>/
  uninstall       archive-then-remove engine-generated files

Public mode installs the synthesis-skills plugin (Claude Code and/or Codex)
and can scaffold a personal knowledge workspace. Org mode adds an
organization's knowledge bases and shared skills, declared in the org's
`.agents/onboarding.yaml` manifest — organizations ship configuration, not
installer code. Schema: references/org-manifest.md beside this skill.

Design rules: python3 stdlib only (PyYAML used when present); idempotent
convergence with receipts at ~/.synthesis/onboarding/receipts.json; conffile
semantics (never clobber user-edited files); archive before every removal;
fail closed and loud on stale caches and unknown manifest keys.
"""

