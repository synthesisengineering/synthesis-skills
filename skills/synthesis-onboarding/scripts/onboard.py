def render_layer_doctor(
    report,
    manifest,
    clients_wanted,
    receipts,
    currency_unverifiable,
):
    catalog = load_catalog(source_root())
    skills_state, skills_detail = _skills_probe(clients_wanted)
    probes = {
        "skills": lambda: (skills_state, skills_detail),
        "session-context": lambda: _session_context_probe(clients_wanted),
        "hooks-gates": lambda: _hooks_probe(clients_wanted),
        "agent-kernel": lambda: _kernel_probe(receipts),
        "runtime-engines": lambda: _runtime_probe(receipts),
        "coordination": _coordination_probe,
        "doctors-conformance": _doctors_probe,
        "personal-policy": _personal_policy_probe,
        "organization": lambda: _organization_probe(manifest, receipts),
        "knowledge-bases": lambda: _knowledge_probe(manifest, receipts),
        "lifecycle": lambda: _lifecycle_probe(
            receipts, skills_state, currency_unverifiable
        ),
    }
    if set(probes) != set(catalog_ids(catalog)):
        report.add("layer", ERROR, "layer catalog and executable probes disagree")
        return False
    unverifiable = False
    for layer in catalog["layers"]:
        layer_id = layer["id"]
        state, detail = probes[layer_id]()
        choice = receipts.layer_choice(layer_id)
        if state is True:
            rendered = "installed"
            verification = "verified"
        elif choice == "declined":
            rendered = "declined"
            verification = "verified"
        else:
            rendered = "missing"
            verification = "unverifiable" if state is None else "verified"
            unverifiable = unverifiable or state is None
        report.add_layer(
            layer_id,
            layer["title"],
            rendered,
            detail,
            verification=verification,
        )
    return unverifiable


def doctor(report, manifest, clients_wanted, policy):
    rc, _, _ = run(["git", "--version"], timeout=15)
    if rc != 0:
        report.add("doctor", ERROR, "git unavailable — cannot verify anything else")
        return 2
    verified_any = False
    currency_unverifiable = False
    target_checked = False
    target_version = None
    target_detail = "not checked"
    for name in clients_wanted:
        binary = resolve_client(name)
        if not binary:
            report.add("doctor", SKIP, "%s not installed" % name)
            continue
        state, installed_version = plugin_record(name, binary)
        fallback = (HOME / (".claude" if name == "claude" else ".agents") / "skills")
        copies = sorted(p.name for p in fallback.glob("synthesis-*")) if fallback.exists() else []
        if state is True:
            verified_any = True
            if not target_checked:
                target_version, target_detail = expected_policy_version(policy)
                target_checked = True
            if target_version is None:
                currency_unverifiable = True
                report.add(
                    "doctor",
                    WARN,
                    "%s: %s plugin enabled at %s; %s is unverifiable" %
                    (name, PLUGIN_NAME, installed_version or "unknown", policy_label(policy)),
                    hint=target_detail,
                )
            elif "stale" in target_detail:
                currency_unverifiable = True
                report.add(
                    "doctor",
                    WARN,
                    "%s: %s plugin %s; %s could not be confirmed live" %
                    (name, PLUGIN_NAME, installed_version or "unknown", policy_label(policy)),
                    hint=target_detail,
                )
            else:
                currency = compare_versions(installed_version, target_version)
                if currency == "current":
                    report.add(
                        "doctor",
                        OK,
                        "%s: %s plugin %s matches %s (%s)" %
                        (name, PLUGIN_NAME, installed_version, policy_label(policy), target_detail),
                    )
                elif currency in ("behind", "ahead"):
                    report.add(
                        "doctor",
                        ACTION,
                        "%s: %s plugin %s is %s; %s resolves to %s" %
                        (name, PLUGIN_NAME, installed_version, currency,
                         policy_label(policy), target_version),
                        hint=(
                            "Close other Claude Code and Codex sessions, then run "
                            "onboard.py update as the invoking session's last action."
                        ),
                    )
                else:
                    currency_unverifiable = True
                    report.add(
                        "doctor",
                        WARN,
                        "%s: %s plugin version is unreadable; %s resolves to %s" %
                        (name, PLUGIN_NAME, policy_label(policy), target_version),
                    )
        elif copies:
            verified_any = True
            report.add("doctor", OK, "%s: %d fallback skill copies present" % (name, len(copies)))
        elif state is None:
            report.add("doctor", WARN, "%s: plugin state could not be read" % name)
        else:
            report.add("doctor", ERROR, "%s: no plugin and no fallback copies" % name)
    if manifest:
        for repo in manifest.get("skills_repos") or []:
            cache = CACHE_DIR / repo["name"]
            if not (cache / ".git").exists():
                report.add("doctor", ERROR, "org skills source %s not present" % repo["name"])
                continue
            status_args = repo.get("status_args")
            if status_args and (cache / repo.get("installer", "install.sh")).exists():
                args = [str(HOME) if a == "$HOME" else a for a in status_args]
                env = {repo["source_env"]: str(cache)} if repo.get("source_env") else None
                rc, out, err = run(["sh", str(cache / repo.get("installer", "install.sh"))] + args, env=env, timeout=300)
                if rc == 0:
                    report.add("doctor", OK, "%s status clean" % repo["name"])
                else:
                    report.add("doctor", ERROR, "%s status reports problems" % repo["name"],
                               hint=(out + err).strip()[-300:])
            else:
                report.add("doctor", OK, "org skills source %s present" % repo["name"])
        receipts = Receipts()
        workspace = manifest["org"]["workspace"]
        for kb in manifest.get("knowledge_bases") or []:
            adopted = receipts.adopted(kb["name"])
            repo_path = Path(adopted) if adopted else WORKSPACES_ROOT / workspace / kb["name"]
            if not (repo_path / ".git").exists():
                report.add("doctor", ERROR, "knowledge base %s not installed" % kb["name"])
                continue
            if origin_url(repo_path) != kb["primary"]:
                report.add("doctor", WARN, "%s origin differs from manifest primary" % kb["name"])
            else:
                report.add("doctor", OK, "knowledge base %s present at %s" % (kb["name"], repo_path))
        ws_agents = WORKSPACES_ROOT / workspace / "AGENTS.md"
        if manifest.get("workspace_instructions") is False:
            pass
        elif ws_agents.exists():
            report.add("doctor", OK, "workspace instructions present")
        else:
            report.add("doctor", ERROR, "workspace AGENTS.md missing — run install")
    layer_unverifiable = render_layer_doctor(
        report,
        manifest,
        clients_wanted,
        Receipts(),
        currency_unverifiable=currency_unverifiable,
    )
    counts = report.counts()
    if counts.get(ERROR):
        return 1
    if counts.get(ACTION):
        return 1
    if currency_unverifiable or layer_unverifiable:
        return 2
    if not verified_any and not manifest:
        return 2
    return 0


