def resolve_client(name):
    env_key = "SYNTHESIS_%s_BIN" % name.upper()
    if env_key in os.environ:
        value = os.environ[env_key].strip()
        return value or None  # set-but-empty means "treat as absent"
    found = shutil.which(name)
    if found:
        return found
    for candidate in CLIENT_WELL_KNOWN.get(name, []):
        if candidate.exists():
            return str(candidate)
    return None


def plugin_record(client, binary):
    rc, out, _ = run([binary, "plugin", "list", "--json"], timeout=60)
    if rc != 0:
        return None, None  # unknown — CLI unavailable or errored
    try:
        entries = json.loads(out)
    except ValueError:
        enabled = PLUGIN_NAME in out and '"enabled": true' in out
        return enabled, None
    if isinstance(entries, dict):
        # claude nests under "plugins"; codex nests under "installed"
        flat = []
        for value in entries.values():
            if isinstance(value, list):
                flat.extend(value)
        entries = flat
    for entry in entries or []:
        if not isinstance(entry, dict) or not entry.get("enabled", False):
            continue
        ident = str(entry.get("id") or entry.get("pluginId") or "")
        if ident.startswith(PLUGIN_NAME + "@") or entry.get("name") == PLUGIN_NAME:
            return True, str(entry.get("version") or "unknown")
    return False, None


def plugin_enabled(client, binary):
    return plugin_record(client, binary)[0]


def source_plugin_version():
    root = source_root()
    for manifest in (root / ".codex-plugin" / "plugin.json",
                     root / ".claude-plugin" / "plugin.json"):
        try:
            return str(json.loads(manifest.read_text(encoding="utf-8"))["version"])
        except (OSError, ValueError, KeyError):
            continue
    return None


def expected_source_plugin_version():
    """Return a release expectation only from an explicit/source checkout.

    An onboarding engine running from an installed plugin cache describes the
    version that is about to be replaced. Comparing the refreshed install to
    that stale manifest would turn a successful upgrade into a false error.
    """
    root = source_root()
    parts = root.resolve().parts
    installed_cache = any(
        parts[index : index + 2] == ("plugins", "cache")
        for index in range(len(parts) - 1)
    )
    if not installed_cache and (
        os.environ.get("SYNTHESIS_ONBOARD_SOURCE_DIR") or (root / ".git").exists()
    ):
        return source_plugin_version()
    return None


def expected_policy_version(policy):
    """Resolve the exact desired version without accepting stale evidence."""
    if policy.get("version_pin"):
        return policy["version_pin"], "exact version pin"
    source_version = expected_source_plugin_version()
    if source_version:
        return source_version, "selected source checkout"
    version, detail = resolve_target_version(policy, ttl_seconds=0)
    if "stale" in detail:
        return None, detail
    return version, detail


