def _main_unlocked(argv=None):
    args = build_parser().parse_args(argv)
    no_services = args.no_services or os.environ.get(
        "SYNTHESIS_ONBOARD_NO_SERVICES"
    ) == "1"
    report = Report(dry_run=args.dry_run, as_json=args.json)
    desired_state = None
    if args.desired_state:
        try:
            desired_state = load_desired_state(args.desired_state)
        except ValueError as exc:
            report.add("desired", ERROR, str(exc))
            return finish(report, args, 2)
    manifest = None
    if args.manifest:
        try:
            manifest = load_manifest(args.manifest)
        except (ValueError, OSError) as exc:
            report.add("manifest", ERROR, str(exc))
            return finish(report, args, 2)
    if (args.personal_instruction_source or args.adopt_workspace_instructions) and not manifest:
        report.add(
            "workspace",
            ERROR,
            "personal instruction sources and workspace adoption require an organization manifest",
        )
        return finish(report, args, 2)
    personal_instruction_source = args.personal_instruction_source
    if desired_state is not None:
        desired_source_path = personal_instruction_source_path(
            desired_state.get("personal_instruction_source")
        )
        if desired_source_path is not None:
            if (
                personal_instruction_source is not None
                and personal_instruction_source.expanduser().resolve()
                != desired_source_path.resolve()
            ):
                report.add(
                    "workspace",
                    ERROR,
                    "personal instruction source differs from persisted desired state",
                )
                return finish(report, args, 2)
            personal_instruction_source = desired_source_path

    try:
        manifest_policy = policy_from_manifest(manifest, channel_override=args.channel)
        policy = normalize_policy(
            manifest_policy["channel"],
            args.version_pin if args.version_pin is not None else manifest_policy["version_pin"],
        )
        clients_wanted = effective_clients(args.clients, manifest)
    except ValueError as exc:
        report.add("manifest", ERROR, str(exc))
        return finish(report, args, 2)
    plugin_requested = ((manifest or {}).get("ecosystem") or {}).get("plugin", True)

    if desired_state and desired_state.get("organizations") and desired_state["organizations"][0].get("mode") == "additive":
        try:
            if not manifest:
                raise ContractError("additive organization requires its declared manifest")
            validate_additive_organization(desired_state, manifest, desired_state["organizations"][0])
        except (ContractError, ValueError) as exc:
            report.add("enroll", ERROR, str(exc))
            return finish(report, args, 2)

    if args.command == "doctor":
        code = doctor(
            report,
            manifest,
            clients_wanted if plugin_requested else [],
            policy,
            desired_state=desired_state,
        )
        return finish(report, args, code)

    if args.command == "kernel":
        receipts = Receipts()
        workspace = args.workspace or receipts.data.get("personal_workspace")
        if not workspace:
            report.add("agent-kernel", ERROR, "--workspace NAME is required until init records one")
            return finish(report, args, 2)
        phase_kernel(report, receipts, workspace, args.dry_run)
        if not args.dry_run:
            receipts.save()
        return finish(report, args, report.exit_code())

    if args.command == "init-workspace":
        if not args.workspace:
            report.add("init-workspace", ERROR, "--workspace NAME is required")
            return finish(report, args, 2)
        receipts = Receipts()
        init_workspace(report, receipts, args.workspace, args.dry_run, remote=args.remote)
        if not args.dry_run:
            receipts.save()
        return finish(report, args, report.exit_code())

    if args.command == "uninstall-doctor":
        verify_uninstalled(report, clients_wanted)
        return finish(report, args, report.exit_code())

    if args.command == "uninstall":
        uninstall(report, args.dry_run, clients_wanted)
        return finish(report, args, report.exit_code())

    journal = None
    if args.command == "enroll":
        if not manifest or not desired_state or not args.enrollment_journal:
            report.add("enroll", ERROR, "enrollment requires a manifest, saved selection, and transaction journal; use synthesis enroll")
            return finish(report, args, 2)
        org_entries = desired_state.get("organizations") or []
        if len(org_entries) != 1 or org_entries[0].get("mode") != "additive":
            report.add("enroll", ERROR, "enrollment requires exactly one additive organization selection")
            return finish(report, args, 2)
        if args.with_personal_workspace or args.profile or args.answers:
            report.add("enroll", ERROR, "enrollment cannot initialize personal layers")
            return finish(report, args, 2)
        try:
            journal = EnrollmentJournal(args.enrollment_journal)
            journal.validate_scope(SystemState(), desired_state)
            if journal.data["state"] != "pending" or journal.data["proposed_desired_digest"] != json_digest(desired_state):
                raise ContractError("enrollment journal does not match proposed desired state")
            journal.capture(RECEIPTS_PATH)
            for name in ("AGENTS.md", "CLAUDE.md"):
                journal.capture(WORKSPACES_ROOT / manifest["org"]["workspace"] / name)
        except (ContractError, OSError, ValueError) as exc:
            report.add("enroll", ERROR, str(exc))
            return finish(report, args, 2)

    # install / additive enrollment / update / whole-system init
    if args.command in ("init", "install", "update", "repair") and not args.dry_run:
        from runtime_payload import recover
        try:
            recover(HOME, STATE_DIR)
        except (ContractError, OSError, ValueError) as exc:
            report.add("shared-runtime", ERROR, "interrupted runtime recovery refused: %s" % exc)
            return finish(report, args, 1)
    receipts = Receipts()
    profile = None
    answers = None
    choices = None
    personal_configuration = None
    if args.command == "init":
        try:
            catalog = load_catalog(source_root())
            profile, answers, choices = collect_init_inputs(args, manifest, catalog)
            if profile == "full":
                personal_configuration = personal_configuration_from_answers(
                    answers
                )
        except (OSError, ValueError) as exc:
            report.add("init", ERROR, str(exc))
            return finish(report, args, 2)
    no_plugin_cli = args.no_plugin_cli or os.environ.get("SYNTHESIS_ONBOARD_NO_PLUGIN_CLI") == "1"
    clients = phase_preflight(report, clients_wanted)
    if clients is None:
        return finish(report, args, 2)
    selected_clients = sorted(name for name, binary in clients.items() if binary)
    if args.command == "init" and not selected_clients:
        report.add("preflight", ERROR, "setup requires at least one installed AI client")
        return finish(report, args, 1)
    if args.command == "enroll":
        validation = Report(dry_run=True, as_json=True)
        phase_workspace(validation, manifest, receipts, True,
                        personal_instruction_source=personal_instruction_source,
                        adopt_existing=args.adopt_workspace_instructions)
        if validation.exit_code():
            report.steps.extend(validation.steps)
            return finish(report, args, validation.exit_code())
    if desired_state is not None and selected_clients != desired_state["clients"]:
        missing = sorted(set(desired_state["clients"]) - set(selected_clients))
        if selected_clients:
            hint = (
                "Install the missing client and re-run, or keep only the present "
                "client(s) with:\n  synthesis setup --clients %s"
                % ",".join(selected_clients)
            )
        else:
            hint = "Install Claude Code or Codex, then re-run synthesis setup."
        report.add(
            "preflight",
            ACTION,
            "desired clients are unavailable: %s" % ", ".join(missing),
            hint=hint,
        )
        return finish(report, args, 1)
    if plugin_requested and args.command != "enroll":
        phase_ecosystem(
            report,
            clients,
            args.dry_run,
            no_plugin_cli,
            policy,
            refresh_native_plugins=args.command in ("update", "repair", "init"),
            preserve_ahead=args.command in ("update", "repair") and not args.policy_transition,
            policy_transition=args.policy_transition,
        )
    elif args.command == "enroll":
        report.add("ecosystem", SKIP, "enrollment preserves the existing public plugin installation")
    else:
        report.add("ecosystem", SKIP, "public plugin disabled by manifest")
    if report.exit_code():
        return finish(report, args, report.exit_code())
    if manifest:
        phase_org_skills(report, manifest, receipts, args.dry_run, clients_wanted, journal)
        if report.exit_code():
            return finish(report, args, report.exit_code())
        phase_kbs(report, manifest, receipts, args.dry_run, enrolling=args.command == "enroll", journal=journal)
        if report.exit_code():
            return finish(report, args, report.exit_code())
        phase_workspace(
            report,
            manifest,
            receipts,
            args.dry_run,
            personal_instruction_source=personal_instruction_source,
            adopt_existing=args.adopt_workspace_instructions,
        )
        if report.exit_code():
            return finish(report, args, report.exit_code())
    if args.with_personal_workspace:
        init_workspace(report, receipts, args.with_personal_workspace, args.dry_run)
    if args.command == "init":
        run_whole_system_init(
            report,
            receipts,
            profile,
            answers,
            choices,
            selected_clients,
            args.dry_run,
            no_services,
        )
    elif args.command == "repair" and desired_state is not None and desired_state["profile"] == "full":
        try:
            repair_answers = reconcile_answers(desired_state, receipts)
        except ValueError as exc:
            report.add("repair", ERROR, str(exc))
            return finish(report, args, 1)
        run_whole_system_init(
            report,
            receipts,
            desired_state["profile"],
            repair_answers,
            desired_state["layers"],
            selected_clients,
            args.dry_run,
            no_services,
        )
    if args.command in ("init", "install", "update", "repair") and not report.exit_code():
        runtime_selection = desired_state
        if args.command == "init":
            runtime_selection = {"layers": choices}
        phase_shared_runtime(report, receipts, runtime_selection, dry_run=args.dry_run)
        if report.exit_code():
            return finish(report, args, report.exit_code())
    if not args.dry_run:
        receipts.data["plugin_policy"] = policy
        receipts.data.setdefault("runs", []).append(
            {"at": utcnow(), "command": args.command, "manifest": str(args.manifest) if args.manifest else None,
             "engine": ENGINE_VERSION})
        receipts.data["runs"] = receipts.data["runs"][-20:]
        try:
            receipts.save()
        except (ContractError, OSError, ValueError) as exc:
            report.add("receipts", ERROR, "receipt save refused: %s" % exc)
            return finish(report, args, 1)
    if args.command == "init" and not args.dry_run and report.exit_code() == 0:
        code = doctor(
            report,
            manifest,
            selected_clients if plugin_requested else [],
            policy,
            desired_state={
                "profile": profile,
                "clients": selected_clients,
                "personal_workspace": answers.get("workspace") or None,
                "personal_configuration": personal_configuration,
                "layers": choices,
            },
        )
    else:
        code = report.exit_code()
    if not args.json:
        counts = report.counts()
        actions = [s for s in report.steps if s["status"] == ACTION]
        print("")
        if actions:
            print("One or more steps need you, then re-run this installer:")
            for step in actions:
                print("  -> %s" % step["detail"])
        elif code == 0:
            phase_welcome(report, manifest)
        summary = ", ".join("%s %s" % (v, k) for k, v in sorted(counts.items()))
        print("Result: %s" % summary)
    effective_selection = None
    if args.command == "init" and code == 0:
        effective_selection = {
            "profile": profile,
            "clients": selected_clients,
            "personal_workspace": answers.get("workspace") or None,
            "personal_configuration": personal_configuration,
            "layers": dict(sorted(choices.items())),
        }
    return finish(report, args, code, effective_selection=effective_selection)


def finish(report, args, code, effective_selection=None):
    if args.json:
        payload = {"engine": ENGINE_VERSION, "dry_run": args.dry_run,
                   "steps": report.steps, "counts": report.counts(),
                   "exit": code}
        if effective_selection is not None:
            payload["effective_selection"] = effective_selection
        print(json.dumps(payload, indent=2))
    return code


