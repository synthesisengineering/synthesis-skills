def kb_agents_md(workspace):
    return """# ai-knowledge-%s

Personal knowledge base for the `%s` workspace, managed with synthesis
project management (three-tier context: CONTEXT.md / REFERENCE.md /
sessions/ per project).

## Structure

```
ai-knowledge-%s/
|-- projects/            # one folder per project + index.yaml registry
|   `-- index.yaml
`-- lessons/             # cross-project lessons, YYYY-MM-DD-slug.md
```

## Rules

- Active projects are listed in `projects/index.yaml` (status lives there,
  not in folder names).
- Each project keeps working memory in `CONTEXT.md` (<=150 lines), stable
  facts in `REFERENCE.md`, history in `sessions/YYYY-MM.md`.
- Lessons are date-prefixed files in `lessons/` — grep them at session start.
""" % (workspace, workspace, workspace)


INDEX_YAML_SEED = """# Projects Index
# Status values: active | paused | ongoing | completed | archived

projects: []
"""

LESSONS_README = """# Lessons

Cross-project lessons and patterns. One file per lesson, named
`YYYY-MM-DD-topic-slug.md`. No index file — `ls -t` shows recent.
"""


def init_workspace(report, receipts, workspace, dry_run, remote=None):
    ws_dir = WORKSPACES_ROOT / workspace
    repo = ws_dir / ("ai-knowledge-%s" % workspace)
    if dry_run:
        report.add("init-workspace", CHANGED, "would scaffold %s" % repo)
        return
    repo.mkdir(parents=True, exist_ok=True)
    ensure_file(report, receipts, repo / "AGENTS.md", kb_agents_md(workspace), "init-workspace", dry_run)
    ensure_file(report, receipts, repo / "CLAUDE.md", "@AGENTS.md\n", "init-workspace", dry_run)
    ensure_file(report, receipts, repo / "README.md",
                "# ai-knowledge-%s\n\nKnowledge base for the %s workspace. See AGENTS.md.\n" % (workspace, workspace),
                "init-workspace", dry_run)
    ensure_file(report, receipts, repo / ".gitignore", ".DS_Store\n", "init-workspace", dry_run)
    projects = repo / "projects"
    projects.mkdir(exist_ok=True)
    ensure_file(report, receipts, projects / "index.yaml", INDEX_YAML_SEED, "init-workspace", dry_run)
    lessons = repo / "lessons"
    lessons.mkdir(exist_ok=True)
    ensure_file(report, receipts, lessons / "README.md", LESSONS_README, "init-workspace", dry_run)
    if not (repo / ".git").exists():
        rc, _, err = git(["init", "-b", "main"], cwd=repo)
        if rc != 0:
            report.add("init-workspace", ERROR, "git init failed", hint=err.strip())
            return
        git(["add", "-A"], cwd=repo)
        rc, _, err = git(["commit", "-m", "Initialize ai-knowledge workspace"], cwd=repo)
        if rc == 0:
            report.add("init-workspace", CHANGED, "initialized git repository with first commit")
        else:
            report.add("init-workspace", ACTION, "repository created; first commit needs your git identity",
                       hint='Run:\n  git config --global user.name "Your Name"\n  git config --global user.email "you@example.com"\nthen commit inside %s' % repo)
    if remote:
        current = origin_url(repo)
        if current is None:
            git(["remote", "add", "origin", remote], cwd=repo)
            report.add("init-workspace", CHANGED, "added origin %s (push when ready)" % remote)
        elif current != remote:
            report.add("init-workspace", WARN, "origin already set to %s — left as-is" % current)


