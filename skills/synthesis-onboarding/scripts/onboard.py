    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("[") and line.endswith("]"):
            in_section = line == "[marketplaces.%s]" % MARKETPLACE_NAME
            continue
        if in_section:
            match = re.match(r'^ref\s*=\s*"([^"]+)"', line)
            if match:
                return match.group(1)
    return None


