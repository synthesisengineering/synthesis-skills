def source_plugin_version():
    root = source_root()
    for manifest in (root / ".codex-plugin" / "plugin.json",
                     root / ".claude-plugin" / "plugin.json"):
        try:
            return str(json.loads(manifest.read_text(encoding="utf-8"))["version"])
        except (OSError, ValueError, KeyError):
            continue
    return None


def expected_source_plugin_version():
    """Return a release expectation only from an explicit/source checkout.

    An onboarding engine running from an installed plugin cache describes the
    version that is about to be replaced. Comparing the refreshed install to
    that stale manifest would turn a successful upgrade into a false error.
    """
    root = source_root()
    parts = root.resolve().parts
    installed_cache = any(
        parts[index : index + 2] == ("plugins", "cache")
        for index in range(len(parts) - 1)
    )
    if not installed_cache and (
        os.environ.get("SYNTHESIS_ONBOARD_SOURCE_DIR") or (root / ".git").exists()
    ):
        return source_plugin_version()
    return None


def expected_policy_version(policy):
    """Resolve the exact desired version without accepting stale evidence."""
    if policy.get("version_pin"):
        return policy["version_pin"], "exact version pin"
    source_version = expected_source_plugin_version()
    if source_version:
        return source_version, "selected source checkout"
    version, detail = resolve_target_version(policy, ttl_seconds=0)
    if "stale" in detail:
        return None, detail
    return version, detail


def marketplace_add_command(client, binary, policy):
    ref = policy_ref(policy)
    if client == "claude":
        return [binary, "plugin", "marketplace", "add", "%s@%s" % (PUBLIC_MARKETPLACE_REF, ref)]
    return [binary, "plugin", "marketplace", "add", PUBLIC_MARKETPLACE_REF, "--ref", ref, "--json"]


def configured_marketplace_ref(client):
    """Return the Git ref the client's public marketplace is configured to track.

    ``None`` means the configuration could not be read or names another
    repository; callers treat that as a reason to reconfigure, never as
    proof of currency.
    """
    try:
        if client == "claude":
            data = json.loads(
                (HOME / ".claude" / "plugins" / "known_marketplaces.json").read_text(
                    encoding="utf-8"
                )
            )
            entry = data.get(MARKETPLACE_NAME) if isinstance(data, dict) else None
            source = entry.get("source") if isinstance(entry, dict) else None
            if isinstance(source, dict) and source.get("repo") == PUBLIC_MARKETPLACE_REF:
                ref = source.get("ref")
                return ref if isinstance(ref, str) and ref else None
            return None
        text = (HOME / ".codex" / "config.toml").read_text(encoding="utf-8")
    except (OSError, ValueError):
        return None
    in_section = False
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("[") and line.endswith("]"):
            in_section = line == "[marketplaces.%s]" % MARKETPLACE_NAME
            continue
        if in_section:
            match = re.match(r'^ref\s*=\s*"([^"]+)"', line)
            if match:
                return match.group(1)
    return None


def refresh_plugin(client, binary, policy, reconfigure=False):
    """Refresh an installed native plugin on the selected release target."""
    if reconfigure:
        commands = [
            [binary, "plugin", "marketplace", "remove", MARKETPLACE_NAME],
            marketplace_add_command(client, binary, policy),
        ]
        verb = "install" if client == "claude" else "add"
        commands.append(
            [binary, "plugin", verb, "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)]
        )
    elif client == "claude":
        commands = [
            [binary, "plugin", "marketplace", "update", MARKETPLACE_NAME],
            [binary, "plugin", "update", "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)],
        ]
    else:
        commands = [
            [binary, "plugin", "marketplace", "upgrade", MARKETPLACE_NAME, "--json"],
            [binary, "plugin", "add", "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)],
        ]
    for command in commands:
        rc, out, err = run(command, timeout=300)
        if rc != 0:
            return False, err.strip() or out.strip() or "exit %d" % rc
    return True, "marketplace and installed plugin refreshed"


def synchronize_codex_history(before_version):
    """Synchronously restore the cache root used by the invoking Codex task.

    A release publisher installs the guardian outside Codex's client-owned
    cache. When that durable runtime is present, an onboarding update consumes
    it before reporting success; the background watcher remains responsible
    for any later cache generation. Machines without the publisher-installed
    recovery archive retain the documented close-other-tasks update contract.
    """
    recovery = (
        HOME
        / ".synthesis"
        / "plugin-cache-recovery"
        / MARKETPLACE_NAME
    )
    runtime = recovery / (".%s-cache-guardian.py" % PLUGIN_NAME)
    if runtime.is_symlink():
        return False, "durable Codex cache guardian has an unsafe type: %s" % runtime
    if not runtime.exists():
        return True, "durable Codex cache guardian is not installed"
    if not runtime.is_file():
        return False, "durable Codex cache guardian has an unsafe type: %s" % runtime
    version = str(before_version or "")
    if VERSION_RE.fullmatch(version) is None:
        return False, "invoking Codex cache version could not be determined"
    rc, out, err = run(
        [sys.executable, str(runtime), "--doctor"],
        env={"HOME": str(HOME)},
        timeout=600,
    )
    if rc != 0:
        return False, err.strip() or out.strip() or "cache guardian exited %d" % rc
    historical = (
        HOME
        / ".codex"
        / "plugins"
        / "cache"
        / MARKETPLACE_NAME
        / PLUGIN_NAME
        / version
    )
    if historical.is_symlink() or not historical.is_dir():
        return False, "invoking Codex cache root %s is absent after guardian verification" % version
    hooks = historical / "hooks" / "hooks.json"
    try:
        hook_text = hooks.read_text(encoding="utf-8")
        json.loads(hook_text)
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        return False, "invoking Codex hook definition is unavailable for %s: %s" % (version, exc)
    targets = sorted(set(HOOK_PLUGIN_PATH_RE.findall(hook_text)))
    missing = [target for target in targets if not (historical / target).is_file()]
    if not targets or missing:
        detail = ", ".join(missing[:3]) if missing else "no plugin-root targets"
        return False, "invoking Codex hook targets are unavailable for %s: %s" % (version, detail)
    return True, "invoking Codex cache root %s restored and verified" % version


def install_plugin(client, binary, policy):
    """Best-effort native plugin install. Returns (success, detail)."""
    add_cmd = marketplace_add_command(client, binary, policy)
    rc, out, err = run(add_cmd, timeout=180)
    if "already" in (out + err).lower():
        remove = [binary, "plugin", "marketplace", "remove", MARKETPLACE_NAME]
        remove_rc, remove_out, remove_err = run(remove, timeout=180)
        if remove_rc != 0:
            return False, "marketplace reconfiguration failed: %s" % (
                remove_err.strip() or remove_out.strip()
            )
        rc, out, err = run(add_cmd, timeout=180)
    if rc != 0:
        return False, "marketplace add failed: %s" % (err.strip() or out.strip())
    verb = "install" if client == "claude" else "add"
    rc, out, err = run([binary, "plugin", verb, "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)], timeout=300)
    if rc != 0 and "already" not in (out + err).lower():
        return False, "plugin %s failed: %s" % (verb, err.strip() or out.strip())
    return True, "installed via %s CLI" % client


