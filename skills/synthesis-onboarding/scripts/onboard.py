def remove_managed_hooks(report, receipts, dry_run):
    """Remove only receipt-owned JSON hook entries before their engines."""
    clean = True
    entries = list(receipts.data.get("managed_json_entries", {}).items())
    for receipt_key, recorded_sha in entries:
        if receipt_key.endswith("#kernel-sync"):
            path = Path(receipt_key[: -len("#kernel-sync")])
            event = "PostToolUse"
            finder = _kernel_sync_entry
            label = "kernel propagation"
        else:
            path = Path(receipt_key)
            event = "PreToolUse"
            finder = _message_guard_entry
            label = "message guard"
        if not path.exists():
            if not dry_run:
                receipts.data["managed_json_entries"].pop(receipt_key, None)
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            clean = False
            report.add(
                "uninstall",
                ACTION,
                "%s cannot be read; no generated files were removed" % path,
                hint=str(exc),
            )
            continue
        current = finder(data)
        if current is None:
            if not dry_run:
                receipts.data["managed_json_entries"].pop(receipt_key, None)
            continue
        if sha256_text(dump_json(current)) != recorded_sha:
            clean = False
            report.add(
                "uninstall",
                ACTION,
                "%s %s entry has user edits; no generated files were removed"
                % (path, label),
            )
            continue
        if dry_run:
            report.add(
                "uninstall", CHANGED, "would remove %s hook from %s" % (label, path)
            )
            continue
        hooks = data.get("hooks", {})
        hooks[event] = [entry for entry in hooks.get(event, []) if entry != current]
        shutil.copy2(path, archive_path(path))
        atomic_json_write(path, data)
        receipts.data["managed_json_entries"].pop(receipt_key, None)
        report.add("uninstall", CHANGED, "removed %s hook from %s" % (label, path))
    text_entries = list(receipts.data.get("managed_text_entries", {}).items())
    for receipt_key, meta in text_entries:
        if not receipt_key.endswith("#codex-hooks-feature"):
            clean = False
            report.add(
                "uninstall", ACTION, "unknown managed text receipt: %s" % receipt_key
            )
            continue
        path = Path(receipt_key[: -len("#codex-hooks-feature")])
        if not path.exists():
            if not dry_run:
                receipts.data["managed_text_entries"].pop(receipt_key, None)
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            clean = False
            report.add("uninstall", ACTION, "%s cannot be read" % path, hint=str(exc))
            continue
        block = managed_codex_hooks_block(text)
        if block is None:
            if not dry_run:
                receipts.data["managed_text_entries"].pop(receipt_key, None)
            continue
        if not isinstance(meta, dict) or sha256_text(block) != meta.get("sha256"):
            clean = False
            report.add(
                "uninstall",
                ACTION,
                "%s Codex hooks feature block has user edits; no generated files were removed"
                % path,
            )
            continue
        if dry_run:
            report.add(
                "uninstall", CHANGED, "would remove owned Codex hooks feature block"
            )
            continue
        updated = text.replace(block + "\n", "", 1)
        if updated == text:
            updated = text.replace(block, "", 1)
        shutil.copy2(path, archive_path(path))
        temporary = path.with_name(".%s.tmp-%s" % (path.name, os.getpid()))
        temporary.write_text(updated, encoding="utf-8")
        os.replace(temporary, path)
        receipts.data["managed_text_entries"].pop(receipt_key, None)
        report.add("uninstall", CHANGED, "removed owned Codex hooks feature block")
    return clean


def _owned_direct_copies(clients_wanted):
    targets = []
    if "claude" in clients_wanted:
        targets.append(HOME / ".claude" / "skills")
    if "codex" in clients_wanted:
        targets.extend((HOME / ".agents" / "skills", HOME / ".codex" / "skills"))
    owned = []
    for target in targets:
        if target.is_symlink() or not target.is_dir():
            continue
        for skill in sorted(target.glob("synthesis-*")):
            provenance = skill / ".source.json"
            if skill.is_symlink() or not skill.is_dir() or not provenance.is_file() or provenance.is_symlink():
                continue
            try:
                source = json.loads(provenance.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if source.get("source_repo") in {
                "github.com/synthesisengineering/synthesis-skills",
                PUBLIC_REPO_HTTPS,
            } and source.get("installed_by") == "install.sh":
                owned.append(skill)
    return owned


def _known_plugin_artifacts(client):
    if client == "claude":
        return [
            HOME / ".claude" / "plugins" / "cache" / MARKETPLACE_NAME / PLUGIN_NAME,
        ]
    return [
        HOME / ".codex" / "plugins" / "cache" / MARKETPLACE_NAME / PLUGIN_NAME,
    ]


def verify_uninstalled(report, clients_wanted):
    clean = True
    for client in clients_wanted:
        binary = resolve_client(client)
        if not binary:
            present = any(path.exists() or path.is_symlink() for path in _known_plugin_artifacts(client))
            if present:
                report.add(
                    "uninstall-verification",
                    ACTION,
                    "%s client is unavailable while plugin artifacts remain" % client,
                )
                clean = False
            else:
                report.add(
                    "uninstall-verification",
                    OK,
                    "%s client is unavailable and has no plugin artifacts" % client,
                )
            continue
        present = plugin_present(client, binary)
        if present is None:
            report.add(
                "uninstall-verification",
                ACTION,
                "%s plugin inventory could not be read" % client,
            )
            clean = False
        elif present:
            report.add(
                "uninstall-verification",
                ACTION,
                "%s public plugin remains installed" % client,
            )
            clean = False
    copies = _owned_direct_copies(clients_wanted)
    if copies:
        report.add(
            "uninstall-verification",
            ACTION,
            "%d receipt-owned direct skill copies remain" % len(copies),
        )
        clean = False
    receipts = Receipts()
    retained = []
    for path_text in receipts.data.get("generated_files", {}):
        path = Path(path_text)
        if path.exists() or path.is_symlink():
            retained.append(path_text)
    for key in receipts.data.get("managed_json_entries", {}):
        path_text = key.split("#", 1)[0]
        path = Path(path_text)
        if path.exists() or path.is_symlink():
            retained.append(path_text)
    for key in receipts.data.get("managed_text_entries", {}):
        path_text = key.split("#", 1)[0]
        path = Path(path_text)
        if path.exists() or path.is_symlink():
            retained.append(path_text)
    if retained:
        report.add(
            "uninstall-verification",
            ACTION,
            "%d receipt-owned generated resources remain" % len(set(retained)),
        )
        clean = False
    if clean:
        report.add(
            "uninstall-verification",
            OK,
            "selected client plugins and receipt-owned direct copies are absent",
            uninstall_verified=True,
        )
    return clean


def _remove_plugins_and_direct_copies(report, clients_wanted, dry_run):
    for client in clients_wanted:
        binary = resolve_client(client)
        if not binary:
            if any(path.exists() or path.is_symlink() for path in _known_plugin_artifacts(client)):
                report.add("uninstall", ACTION, "%s client is unavailable while plugin artifacts remain" % client)
            else:
                report.add("uninstall", OK, "%s has no installed plugin artifacts" % client)
            continue
        present = plugin_present(client, binary)
        if present is None:
            report.add("uninstall", ACTION, "%s plugin inventory could not be read" % client)
            continue
        if not present:
            report.add("uninstall", OK, "%s public plugin is already absent" % client)
            continue
        if dry_run:
            report.add("uninstall", CHANGED, "would remove %s public plugin" % client)
            continue
        identifier = "%s@%s" % (PLUGIN_NAME, MARKETPLACE_NAME)
        command = (
            [binary, "plugin", "uninstall", identifier, "--yes"]
            if client == "claude"
            else [binary, "plugin", "remove", identifier, "--json"]
        )
        rc, out, err = run(command, timeout=300)
        if rc != 0:
            report.add(
                "uninstall",
                ACTION,
                "%s public plugin removal failed" % client,
                hint=(err.strip() or out.strip() or "exit %d" % rc),
            )
            continue
        report.add("uninstall", CHANGED, "removed %s public plugin" % client)

    for skill in _owned_direct_copies(clients_wanted):
        if dry_run:
            report.add("uninstall", CHANGED, "would archive and remove %s" % skill)
            continue
        relative_tag = hashlib.sha256(str(skill.parent).encode("utf-8")).hexdigest()[:12]
        destination = archive_path(skill).with_name("%s-%s" % (relative_tag, skill.name))
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(skill, destination)
        if paths_digest([skill]) != paths_digest([destination]):
            shutil.rmtree(destination)
            report.add("uninstall", ACTION, "direct-copy backup verification failed for %s" % skill)
            continue
        shutil.rmtree(skill)
        report.add("uninstall", CHANGED, "archived and removed %s" % skill)


def uninstall(report, dry_run, clients_wanted=None):
    clients_wanted = list(clients_wanted or ["claude", "codex"])
    receipts = Receipts()
    hooks_clean = remove_managed_hooks(report, receipts, dry_run)
    files = list(receipts.data.get("generated_files", {}).items())
    if not files and not receipts.data.get("managed_json_entries"):
        report.add("uninstall", OK, "nothing recorded to remove")
    if not hooks_clean:
        if not dry_run:
            receipts.save()
        report.add(
            "uninstall",
            ACTION,
            "resolve the edited hook entry, then re-run uninstall; generated files remain intact",
        )
        return
    for path_str, meta in files:
        path = Path(path_str)
        if not path.exists():
            receipts.forget_file(path)
            continue
        current = path.read_text(encoding="utf-8")
        if sha256_text(current) != meta.get("sha256"):
            report.add("uninstall", WARN, "%s was edited after install — left in place" % path)
            continue
        if dry_run:
            report.add("uninstall", CHANGED, "would archive and remove %s" % path)
            continue
        shutil.copy2(path, archive_path(path))
        path.unlink()
        receipts.forget_file(path)
        report.add("uninstall", CHANGED, "archived and removed %s" % path)
    if not dry_run:
        receipts.save()
    _remove_plugins_and_direct_copies(report, clients_wanted, dry_run)
    if not dry_run:
        verify_uninstalled(report, clients_wanted)
    report.add(
        "uninstall",
        OK,
        "knowledge-base clones are retained as user data",
    )


def load_desired_state(path):
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError("desired state is unreadable: %s" % exc)
    try:
        return validate_desired_state(value)
    except ContractError as exc:
        raise ValueError(str(exc))


