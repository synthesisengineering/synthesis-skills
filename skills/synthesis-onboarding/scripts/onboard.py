def phase_preflight(report, clients_wanted):
    platform = platform_family()
    if platform == "native-windows":
        report.add(
            "preflight",
            ERROR,
            "native Windows is not supported; run the installer inside WSL",
        )
        return None
    if platform == "unsupported":
        report.add(
            "preflight",
            ERROR,
            "unsupported platform %s; this release supports macOS and Linux userlands"
            % sys.platform,
        )
        return None
    if platform == "wsl":
        report.add("preflight", OK, "Windows detected through the supported WSL userland")
    elif platform == "linux":
        report.add("preflight", OK, "Linux userland detected")
    else:
        report.add("preflight", OK, "macOS detected")
    rc, out, _ = run(["git", "--version"], timeout=15)
    if rc != 0:
        report.add("preflight", ERROR, "git is not available",
                   hint="On macOS run:  xcode-select --install\nThen re-run this installer.")
        return None
    report.add("preflight", OK, out.strip())
    clients = {}
    for name in clients_wanted:
        binary = resolve_client(name)
        clients[name] = binary
        if binary:
            report.add("preflight", OK, "%s found: %s" % (name, binary))
        else:
            report.add("preflight", SKIP, "%s not found — skipping that client" % name,
                       hint="Install Claude Code or the ChatGPT app to use the skills there, then re-run.")
    if not any(clients.values()):
        report.add("preflight", WARN, "no AI client detected; repos and workspace will still be set up")
    return clients


def platform_family(platform=None, environ=None, proc_version=None):
    platform = platform or sys.platform
    environ = environ if environ is not None else os.environ
    if platform == "darwin":
        return "macos"
    if platform.startswith("linux"):
        version = proc_version
        if version is None:
            try:
                version = Path("/proc/version").read_text(encoding="utf-8")
            except OSError:
                version = ""
        if environ.get("WSL_INTEROP") or environ.get("WSL_DISTRO_NAME") or "microsoft" in version.lower():
            return "wsl"
        return "linux"
    if platform in ("win32", "cygwin"):
        return "native-windows"
    return "unsupported"


def phase_ecosystem(
    report,
    clients,
    dry_run,
    no_plugin_cli,
    policy,
    refresh_native_plugins=False,
    preserve_ahead=False,
    policy_transition=False,
):
    """Public synthesis-skills into each present client; fallback to install.sh."""
    need_fallback = False
    for name, binary in clients.items():
        if not binary:
            continue
        state, before_version = plugin_record(name, binary)
        if state is True:
            if no_plugin_cli:
                report.add(
                    "ecosystem", OK,
                    "%s plugin enabled for %s at %s; refresh skipped by flag" %
                    (PLUGIN_NAME, name, before_version or "unknown version"),
                )
                continue
            expected, expectation_detail = expected_policy_version(policy)
            if not refresh_native_plugins:
                if expected and before_version != expected:
                    report.add(
                        "ecosystem", ACTION,
                        "%s plugin for %s is %s; source is %s" %
                        (PLUGIN_NAME, name, before_version, expected),
                        hint=(
                            "Close other Claude Code and Codex sessions, then run "
                            "onboard.py update as the invoking session's last action."
                        ),
                    )
                else:
                    report.add(
                        "ecosystem", OK,
                        "%s plugin enabled for %s at %s" %
                        (PLUGIN_NAME, name, before_version or "unknown version"),
                    )
                continue
            if dry_run:
                report.add(
                    "ecosystem", CHANGED,
                    "would refresh %s plugin for %s" % (PLUGIN_NAME, name),
                )
                continue
            if (
                preserve_ahead
                and not policy.get("version_pin")
                and expected
                and before_version
                and semver_tuple(before_version) is not None
                and semver_tuple(expected) is not None
                and semver_tuple(before_version) > semver_tuple(expected)
            ):
                report.add(
                    "ecosystem",
                    OK,
                    "%s plugin for %s is %s, ahead of floating %s at %s; kept installed version"
                    % (PLUGIN_NAME, name, before_version, policy.get("channel"), expected),
                )
                continue
            configured_ref = configured_marketplace_ref(name)
            if (
                not policy_transition
                and expected
                and before_version == expected
                and configured_ref == policy_ref(policy)
            ):
                # Removing and re-adding the marketplace is the destructive
                # step that forces a Codex cache refresh; a current install on
                # the selected ref has nothing to refresh.
                report.add(
                    "ecosystem",
                    OK,
                    "%s plugin current for %s at %s on the %s ref; no refresh needed"
                    % (PLUGIN_NAME, name, before_version, configured_ref),
                )
                continue
            success, detail = refresh_plugin(
                name,
                binary,
                policy,
                reconfigure=True,
            )
            if not success:
                report.add(
                    "ecosystem", ERROR,
                    "%s plugin refresh failed for %s" % (PLUGIN_NAME, name),
                    hint=detail,
                )
                continue
            if name == "codex":
                history_ok, history_detail = synchronize_codex_history(before_version)
                if not history_ok:
                    report.add(
                        "ecosystem",
                        ERROR,
                        "%s historical cache preservation failed for %s" %
                        (PLUGIN_NAME, name),
                        hint=history_detail,
                    )
                    continue
            after_state, after_version = plugin_record(name, binary)
            if after_state is not True:
                report.add("ecosystem", ERROR,
                           "%s plugin disappeared after refresh for %s" % (PLUGIN_NAME, name))
            elif expected and after_version != expected:
                report.add(
                    "ecosystem", ERROR,
                    "%s plugin for %s is %s after refresh; expected %s" %
                    (PLUGIN_NAME, name, after_version, expected),
                )
            elif expected is None:
                report.add(
                    "ecosystem",
                    ERROR,
                    "%s plugin refreshed for %s at %s, but %s could not be verified" %
                    (PLUGIN_NAME, name, after_version or "unknown", policy_label(policy)),
                    hint=expectation_detail,
                )
            elif after_version != before_version:
                restart = "restart Claude Code" if name == "claude" else "restart Codex"
                report.add(
                    "ecosystem", CHANGED,
                    "%s plugin updated for %s: %s -> %s; %s, then start a new chat there" %
                    (PLUGIN_NAME, name, before_version, after_version, restart),
                )
            else:
                report.add(
                    "ecosystem", OK,
                    "%s plugin current for %s at %s; no new task needed" %
                    (PLUGIN_NAME, name, after_version or "unknown version"),
                )
            continue
        if no_plugin_cli:
            need_fallback = True
            report.add("ecosystem", WARN, "plugin CLI disabled by flag for %s; using file fallback" % name)
            continue
        if dry_run:
            report.add("ecosystem", CHANGED, "would install %s plugin via %s CLI" % (PLUGIN_NAME, name))
            continue
        success, detail = install_plugin(name, binary, policy)
        after_state, after_version = plugin_record(name, binary)
        expected, expectation_detail = expected_policy_version(policy)
        if success and after_state is True and expected and after_version != expected:
            report.add(
                "ecosystem",
                ERROR,
                "%s installed for %s at %s; %s resolves to %s" %
                (PLUGIN_NAME, name, after_version or "unknown", policy_label(policy), expected),
            )
        elif success and after_state is True and expected is None:
            report.add(
                "ecosystem",
                ERROR,
                "%s installed for %s at %s, but %s could not be verified" %
                (PLUGIN_NAME, name, after_version or "unknown", policy_label(policy)),
                hint=expectation_detail,
            )
        elif success and after_state is True:
            restart = "restart Claude Code" if name == "claude" else "restart Codex"
            report.add(
                "ecosystem", CHANGED,
                "%s: %s; %s, then start a new chat there" %
                (name, detail, restart),
            )
        else:
            need_fallback = True
            report.add("ecosystem", WARN, "%s plugin CLI route failed; using file fallback" % name,
                       hint=detail)
    if need_fallback:
        installer = source_root() / "install.sh"
        if not installer.exists():
            report.add("ecosystem", ERROR, "fallback installer missing at %s" % installer)
            return
        if dry_run:
            report.add("ecosystem", CHANGED, "would run fallback: sh %s install" % installer)
            return
        # A clean `status` alone is not proof of an install: on a machine
        # where the target directories do not exist yet, status has nothing
        # to check and exits 0. Require actual copies before skipping.
        rc, _, _ = run(["sh", str(installer), "status"], timeout=300)
        copies_present = any(
            target.is_dir() and any(target.glob("synthesis-*"))
            for target in (HOME / ".claude" / "skills", HOME / ".agents" / "skills"))
        if rc == 0 and copies_present:
            report.add("ecosystem", OK, "fallback skill copies already current")
            return
        rc, out, err = run(["sh", str(installer), "install"], timeout=600)
        if rc == 0:
            report.add("ecosystem", CHANGED, "fallback skill copies installed (install.sh)")
        else:
            report.add("ecosystem", ERROR, "fallback install.sh failed", hint=(err or out).strip()[-400:])


