def phase_preflight(report, clients_wanted):
    if sys.platform != "darwin":
        report.add("preflight", WARN, "v1 targets macOS; this platform (%s) is best-effort" % sys.platform)
    rc, out, _ = run(["git", "--version"], timeout=15)
    if rc != 0:
        report.add("preflight", ERROR, "git is not available",
                   hint="On macOS run:  xcode-select --install\nThen re-run this installer.")
        return None
    report.add("preflight", OK, out.strip())
    clients = {}
    for name in clients_wanted:
        binary = resolve_client(name)
        clients[name] = binary
        if binary:
            report.add("preflight", OK, "%s found: %s" % (name, binary))
        else:
            report.add("preflight", SKIP, "%s not found — skipping that client" % name,
                       hint="Install Claude Code or the ChatGPT app to use the skills there, then re-run.")
    if not any(clients.values()):
        report.add("preflight", WARN, "no AI client detected; repos and workspace will still be set up")
    return clients


def phase_ecosystem(report, clients, dry_run, no_plugin_cli):
    """Public synthesis-skills into each present client; fallback to install.sh."""
    need_fallback = False
    for name, binary in clients.items():
        if not binary:
            continue
        state = plugin_enabled(name, binary)
        if state is True:
            report.add("ecosystem", OK, "%s plugin already enabled (%s)" % (PLUGIN_NAME, name))
            continue
        if no_plugin_cli:
            need_fallback = True
            report.add("ecosystem", WARN, "plugin CLI disabled by flag for %s; using file fallback" % name)
            continue
        if dry_run:
            report.add("ecosystem", CHANGED, "would install %s plugin via %s CLI" % (PLUGIN_NAME, name))
            continue
        success, detail = install_plugin(name, binary)
        if success and plugin_enabled(name, binary):
            report.add("ecosystem", CHANGED, "%s: %s" % (name, detail))
        else:
            need_fallback = True
            report.add("ecosystem", WARN, "%s plugin CLI route failed; using file fallback" % name,
                       hint=detail)
    if need_fallback:
        installer = source_root() / "install.sh"
        if not installer.exists():
            report.add("ecosystem", ERROR, "fallback installer missing at %s" % installer)
            return
        if dry_run:
            report.add("ecosystem", CHANGED, "would run fallback: sh %s install" % installer)
            return
        # A clean `status` alone is not proof of an install: on a machine
        # where the target directories do not exist yet, status has nothing
        # to check and exits 0. Require actual copies before skipping.
        rc, _, _ = run(["sh", str(installer), "status"], timeout=300)
        copies_present = any(
            target.is_dir() and any(target.glob("synthesis-*"))
            for target in (HOME / ".claude" / "skills", HOME / ".agents" / "skills"))
        if rc == 0 and copies_present:
            report.add("ecosystem", OK, "fallback skill copies already current")
            return
        rc, out, err = run(["sh", str(installer), "install"], timeout=600)
        if rc == 0:
            report.add("ecosystem", CHANGED, "fallback skill copies installed (install.sh)")
        else:
            report.add("ecosystem", ERROR, "fallback install.sh failed", hint=(err or out).strip()[-400:])


def phase_org_skills(report, manifest, dry_run):
    for repo in manifest.get("skills_repos") or []:
        cache = CACHE_DIR / repo["name"]
        urls = [repo["primary"]] + list(repo.get("fallbacks") or [])
        status = clone_or_update(report, "org-skills", urls, cache, dry_run)
        if status in (ERROR,):
            continue
        installer_rel = repo.get("installer")
        if not installer_rel:
            continue
        installer = cache / installer_rel
        args = [str(HOME) if a == "$HOME" else a for a in (repo.get("installer_args") or [])]
        if dry_run or status == WOULD:
            report.add("org-skills", CHANGED, "would run %s %s" % (installer, " ".join(args)))
            continue
        if not installer.exists():
            report.add("org-skills", ERROR, "installer %s not found in %s" % (installer_rel, repo["name"]))
            continue
        env = {}
        if repo.get("source_env"):
            env[repo["source_env"]] = str(cache)
        status_args = repo.get("status_args")
        if status_args:
            probe = [str(HOME) if a == "$HOME" else a for a in status_args]
            rc, _, _ = run(["sh", str(installer)] + probe, env=env, timeout=300)
            if rc == 0:
                report.add("org-skills", OK, "%s already installed and clean" % repo["name"])
                continue
        rc, out, err = run(["sh", str(installer), "install"] + args, env=env, timeout=600)
        if rc == 0:
            report.add("org-skills", CHANGED, "%s installer completed" % repo["name"])
        else:
            report.add("org-skills", ERROR, "%s installer failed" % repo["name"],
                       hint=(err or out).strip()[-400:])


def find_adoptable(name, primary, superseded):
    """Search shallow workspace paths for an existing clone of this repo."""
    wanted = {primary} | set(superseded or [])
    candidates = []
    if WORKSPACES_ROOT.exists():
        candidates.extend(WORKSPACES_ROOT.glob("*/%s" % name))
        candidates.extend(WORKSPACES_ROOT.glob(name))
    for candidate in candidates:
        if (candidate / ".git").exists() and origin_url(candidate) in wanted:
            return candidate
    return None


def phase_kbs(report, manifest, receipts, dry_run):
    workspace = manifest["org"]["workspace"]
    auth_help = (manifest.get("auth_help") or "").strip()
    for kb in manifest.get("knowledge_bases") or []:
        name, primary = kb["name"], kb["primary"]
        superseded = kb.get("superseded_remotes") or []
        standard = WORKSPACES_ROOT / workspace / name
        adopted = receipts.adopted(name)
        repo = Path(adopted) if adopted and Path(adopted, ".git").exists() else None
        if repo is None and (standard / ".git").exists():
            repo = standard
        if repo is None:
            found = find_adoptable(name, primary, superseded)
            if found is not None:
                repo = found
                receipts.record_adoption(name, found)
                report.add("knowledge-base", OK, "adopted existing clone of %s at %s" % (name, found))
        if repo is None:
            if dry_run:
                report.add("knowledge-base", CHANGED, "would clone %s -> %s" % (primary, standard))
                continue
            rc, _, err = git(["ls-remote", primary], timeout=60)
            if rc != 0:
                report.add("knowledge-base", ACTION, "cannot reach %s yet — one step needs you" % name,
                           hint=(auth_help or "Set up your git access for %s, then re-run this installer." % primary))
                continue
            standard.parent.mkdir(parents=True, exist_ok=True)
            rc, _, err = git(["clone", primary, str(standard)], timeout=900)
            if rc != 0:
                report.add("knowledge-base", ERROR, "clone of %s failed" % name, hint=err.strip()[-400:])
                continue
            repo = standard
            report.add("knowledge-base", CHANGED, "cloned %s -> %s" % (name, standard))
        current_origin = origin_url(repo)
        if current_origin in superseded:
            if dry_run:
                report.add("knowledge-base", CHANGED, "would repoint %s origin -> %s" % (name, primary))
            else:
                git(["remote", "set-url", "origin", primary], cwd=repo)
                report.add("knowledge-base", CHANGED, "repointed %s origin to the current primary remote" % name)
        elif current_origin != primary:
            report.add("knowledge-base", WARN, "%s origin is %s (expected %s) — left as-is" % (name, current_origin, primary))
        if not dry_run:
            if is_dirty(repo):
                report.add("knowledge-base", WARN, "%s has local changes; skipped pull" % name)
            else:
                rc, _, err = git(["pull", "--ff-only"], cwd=repo, timeout=300)
                if rc == 0:
                    report.add("knowledge-base", OK, "%s is up to date" % name)
                else:
                    report.add("knowledge-base", WARN, "%s could not fast-forward" % name,
                               hint=err.strip()[-300:] if err else None)
        if kb.get("local_hooks") and (Path(repo) / ".githooks").is_dir():
            rc, out, _ = git(["config", "--global", "--get", "core.hooksPath"])
            if rc == 0 and out.strip():
                report.add("knowledge-base", OK, "global git hooks engine already active; not overriding")
            else:
                rc, out, _ = git(["config", "--local", "--get", "core.hooksPath"], cwd=repo)
                if out.strip() == ".githooks":
                    report.add("knowledge-base", OK, "%s pre-commit protection wired" % name)
                elif dry_run:
                    report.add("knowledge-base", CHANGED, "would wire %s repo-local hooks (.githooks)" % name)
                else:
                    git(["config", "--local", "core.hooksPath", ".githooks"], cwd=repo)
                    report.add("knowledge-base", CHANGED, "wired %s repo-local pre-commit protection" % name)


