def test_the_command_line(tmp_path):
    schema = cli("--schema")
    assert schema.returncode == 0 and schema.stdout == (SKILL / "assets" / "spec-schema.txt").read_text(encoding="utf-8")
    path = write(tmp_path, spec())
    out = cli(path, "--stdout")
    assert out.returncode == 0 and out.stdout == bs.build(spec())
    piped = cli("-", "--stdout", stdin=json.dumps(spec()))
    assert piped.returncode == 0 and piped.stdout == out.stdout
    made = cli(path, "-o", tmp_path / "work" / "sheet.html")
    assert made.returncode == 0 and "1 to approve, 5 to do, 1 done for you" in made.stdout
    assert (tmp_path / "work" / "sheet.html").read_text(encoding="utf-8") == out.stdout
    assert cli(path, "--date", "2026-10-19").returncode == 2  # --date needs --file-into
    assert cli(path, "--file-into", tmp_path / "missing").returncode == 2
    assert cli(path, "--file-into", tmp_path, "--date", "2026-13-01").returncode == 2
    (tmp_path / "dup.json").write_text('{"title": "a", "title": "b"}', encoding="utf-8")
    assert "duplicate JSON key" in cli(tmp_path / "dup.json", "--stdout").stderr


