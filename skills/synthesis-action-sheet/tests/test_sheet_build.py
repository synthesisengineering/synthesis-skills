def test_filing_uses_the_packets_dated_names_and_never_replaces(tmp_path):
    artifacts = tmp_path / "resources" / "artifacts"
    artifacts.mkdir(parents=True)
    current = spec()
    result = cli(write(tmp_path, current), "--file-into", artifacts, "--date", "2026-10-19")
    assert result.returncode == 0, result.stderr
    spec_copy, page_copy = artifacts / "2026-10-19-synthetic-actions-spec.json", artifacts / "2026-10-19-synthetic-actions.html"
    assert f"filed {spec_copy}" in result.stdout and f"filed {page_copy}" in result.stdout
    assert spec_copy.read_bytes() == bs.canonical_spec_bytes(current)
    assert cli(write(tmp_path, current), "--file-into", artifacts, "--date", "2026-10-19").returncode == 0  # identical
    revised = copy.deepcopy(current)
    row(revised, "D-1")["text"] = "Sam, dinner at 8?"
    assert cli(write(tmp_path, revised), "--file-into", artifacts, "--date", "2026-10-19").returncode == 0
    assert spec_copy.read_bytes() == bs.canonical_spec_bytes(current)  # the first filing is preserved
    assert len(list(artifacts.glob("2026-10-19-synthetic-actions-*-spec.json"))) == 1


