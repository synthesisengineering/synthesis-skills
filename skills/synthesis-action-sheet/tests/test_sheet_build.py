MARKER = re.compile(r"<!-- synthesis-action-sheet spec-sha256:([0-9a-f]{64}) -->")
EMBEDDED = re.compile(r'<script type="application/json" id="spec">(.*?)</script>', re.S)


def spec():
    """A small synthetic sheet: one staged send and one row of each kind the principal does."""
    return {
        "title": "Synthetic actions",
        "done": [{"kind": "emails sent", "label": "Sent the fixture note", "href": "https://mail.example.test/1"}],
        "approve": [{"id": "A-1", "channel": "email", "who": "Jordan Example", "address": "jordan@example.test",
                     "why": "Fixture send.", "text": "Hello Jordan."}],
        "do": [
            {"id": "D-1", "channel": "whatsapp", "who": "Sam Placeholder", "address": "+15555550123",
             "why": "Fixture message.", "text": "Sam, dinner at 7?", "agent": "can"},
            {"id": "D-2", "channel": "imessage", "who": "Pat Example", "address": "+15555550142",
             "why": "Fixture message.", "text": "Tea on Sunday?", "agent": "can"},
            {"id": "D-3", "channel": "linkedin", "who": "Alex Example", "why": "Fixture message.",
             "text": "Coffee on Tuesday?", "agent": "never"},
            {"id": "D-4", "channel": "web", "label": "Pay the fixture deposit", "href": "https://bank.example.test/pay",
             "why": "Fixture task.", "agent": "never", "risk": "money"},
            {"id": "D-5", "channel": "task", "label": "Sign the fixture form", "why": "Fixture task.", "agent": "never"},
        ],
    }


def cli(*args, stdin=None):
    return subprocess.run([sys.executable, str(SCRIPTS / "build_sheet.py"), *map(str, args)],
                          input=stdin, capture_output=True, text=True)


def write(tmp_path, value, name="spec.json"):
    path = tmp_path / name
    path.write_text(json.dumps(value, ensure_ascii=False), encoding="utf-8")
    return path


def row(current, rid):
    return next(r for section in ("approve", "do") for r in current.get(section, []) if r["id"] == rid)


