class _Links(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.row = [], None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "article":
            self.row = int(attrs["data-row"])
        if tag == "a" and "btn" in (attrs.get("class") or ""):
            self.links.append((self.row, attrs["href"], attrs.get("target"), attrs.get("rel")))


def test_the_page_shows_exactly_the_links_the_generator_built():
    current = spec()
    page = bs.build(current)
    reader = _Links()
    reader.feed(page)
    rows = current["approve"] + current["do"]
    expected = [(i, bs.open_link(r)) for i, r in enumerate(rows) if "agent" in r and bs.open_link(r)]
    assert [(i, h) for i, h, _, _ in reader.links] == [(i, link["href"]) for i, link in expected]
    for (_, href, target, rel), (_, link) in zip(reader.links, expected):
        # https opens a new tab; a custom scheme stays in place for the operating system to hand off.
        assert (target, rel) == ((None, None) if link["custom"] else ("_blank", "noopener noreferrer"))
        assert urllib.parse.urlsplit(href).scheme in bs.SCHEMES


