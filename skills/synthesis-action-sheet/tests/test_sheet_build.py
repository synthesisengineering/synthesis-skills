def test_the_shipped_example_builds_with_every_section():
    example = json.loads((SKILL / "assets" / "example-spec.json").read_text(encoding="utf-8"))
    assert bs.validate(example) == []
    page = bs.build(example)
    for part in ('<details class="done" id="done">', 'id="approve"', 'id="do"', "Copy summary", "Who does it"):
        assert part in page
    assert "3 emails sent \u00b7 2 calendar holds \u00b7 2 records filed" in page


def test_charset_comes_first_and_typography_survives():
    """Without the charset first, typographic punctuation turns to mojibake over a plain local server."""
    current = spec()
    row(current, "D-1")["text"] = "Don\u2019t \u201cconverge\u201d \u2014 Sam\u2026"
    page = bs.build(current)
    assert '<meta charset="utf-8">' in page[:200] and page.index("<meta charset") < page.index("<title")
    embedded = json.loads(EMBEDDED.search(page).group(1))
    assert embedded["do"][0]["text"] == row(current, "D-1")["text"]


def test_marker_pins_the_embedded_spec_in_the_packet_form():
    page = bs.build(spec())
    marker, embedded = MARKER.search(page), EMBEDDED.search(page)
    assert marker and embedded
    assert hashlib.sha256(embedded.group(1).encode("utf-8")).hexdigest() == marker.group(1)
    assert page.index("</title>\n") + len("</title>\n") == page.index(marker.group(0)) < page.index("<style>")


def test_saved_marks_are_keyed_to_the_exact_spec_digest():
    current = spec()
    page = bs.build(current)
    assert f'var SPEC_DIGEST = "{bs.spec_digest(current)}";' in page
    assert 'var KEY = "action-sheet:" + SPEC.storage_key + ":" + SPEC_DIGEST;' in page
    assert json.loads(EMBEDDED.search(page).group(1))["storage_key"] == "synthetic-actions"
    changed = spec()
    row(changed, "D-1")["why"] = "A different reason."
    assert bs.spec_digest(changed) != bs.spec_digest(current)  # any change starts fresh marks


def test_a_fresh_sheet_presses_nothing():
    body = bs.build(spec()).split("<body", 1)[1].split('<script type="application/json"', 1)[0]
    assert 'aria-pressed="true"' not in body and 'aria-pressed="false"' in body


def test_the_summary_words_come_from_the_generator():
    """The page reads every word of its summary from the embedded spec, so the recorder and the page
    cannot drift apart."""
    page = bs.build(spec())
    assert json.loads(EMBEDDED.search(page).group(1))["format"] == bs.SUMMARY
    script = page[page.index("<script>"):]
    f = bs.SUMMARY
    phrases = (list(f["headings"].values()) + [f["status_prefix"], f["note_prefix"], f["storage"], f["binding"]]
               + list(f["approve"].values()) + list(f["do"].values())
               + [label for section in f["counts"].values() for _, label in section])
    states = {"open", "done", "skipped"}  # also the page's state names, which it must spell
    assert [p for p in phrases if p not in states and json.dumps(p) in script] == []


def test_spec_text_stays_text():
    current = spec()
    row(current, "D-1")["text"] = "literal </script><script>window.injected=true</script> <!--<script> __TITLE__"
    page = bs.build(current)
    assert "</script><script>window.injected" not in page
    assert "\\u003c/script>" in EMBEDDED.search(page).group(1)
    assert "__TITLE__" in page.split("<body", 1)[1]  # a placeholder in spec text is never substituted


